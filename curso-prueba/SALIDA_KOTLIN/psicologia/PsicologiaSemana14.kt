| :--- | :--- | :--- | :--- | :--- |
| **Oral** | 0 - 1.5\text{ años} | Boca, labios, lengua | Destete; placer por succión, mordisqueo y alimentación. | Tabaquismo, alcoholismo, comerse las uñas, dependencia pasiva u optimismo ingenuo. |
