## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS LINGÜÍSTICOS
1. **Diatópico**: Relativo a la variación espacial o territorial de una lengua (dialecto).
2. **Diastrático**: Relativo a la variación en los estratos sociales y culturales de los hablantes (sociolecto).
3. **Diafásico**: Relativo a los registros de situación, edad o profesión del individuo (idiolecto).
4. **Tecnolecto**: Vocabulario técnico o jerga especializada propia de una profesión o disciplina científica.
5. **Lengua Estándar**: Modelo lingüístico institucionalizado y normado que asegura la inteligibilidad mutua de una comunidad idiomática.
6. **Diglosia**: Convivencia desequilibrada de dos lenguas donde una goza de estatus oficial hegemónico y la otra sufre marginación social.
7. **Motoseo**: Fenómeno fonético de interferencia en el cual un hablante quechua o aimara sustituye timbres vocálicos al hablar español.
8. **Replana**: Argot o jerga marginal y delictiva que utiliza vocablos deformados o cifrados fuera de la norma culta.
9. **Lengua Amerindia**: Lengua nativa y originaria del continente americano previa a la llegada europea del siglo XVI.
10. **EIB**: Educación Intercultural Bilingüe, modelo pedagógico estatal que respeta y enseña en la lengua originaria materna.

