#### 1. Las Lenguas Amerindias Andinas
Pertenecen a dos grandes familias lingüísticas nativas:
- **A. Familia Lingüística Quechua (Runa Simi)**:
  - Es la **lengua originaria más hablada del Perú y de toda América del Sur** (más de 3.5 millones de quechuahablantes en el país).
  - No es una lengua única homogénea, sino una **familia lingüística** con diversas variedades agrupadas según Alfredo Torero en dos ramas:
    1. *Quechua I o Central* (Waywash): Hablado en Áncash, Huánuco, Pasco, Junín y Lima provincias. Es la rama más arcaica.
    2. *Quechua II o Periférico* (Wampuy):
       - *Quechua Norteño*: Cajamarca, Lambayeque (Incahuasi, Cañaris), Chachapoyas.
       - *Quechua Sureño*: Cuzco, Puno, Ayacucho, Apurímac, Arequipa y Huancavelica (variedades Chanca y Collao). Es la variedad con mayor número de hablantes y literatura.
       - *Quechua de la Selva*: San Martín (Lamas), Loreto, Madre de Dios.
- **B. Familia Lingüística Aru**:
  - Agrupa a lenguas andinas milenarias:
    1. **El Aimara**: Segunda lengua originaria más hablada del Perú. Concentrada en el altiplano del lago Titicaca (departamento de Puno), con presencia en Moquegua, Tacna y Arequipa.
    2. **El Jacaru y el Cauqui**: Habladas históricamente en la provincia de **Yauyos (departamento de Lima)** (distrito de Tupe). El cauqui se encuentra prácticamente extinto y el jacaru en estado crítico de vulnerabilidad.

#### 2. Las Lenguas Amerindias Amazónicas
La Amazonía peruana es el **área de mayor diversidad y fragmentación etnolingüística del país** (alberga a más de 40 etnias y 44 lenguas agrupadas en aproximadamente 17 a 19 familias lingüísticas).
- Principales Familias y Lenguas Amazónicas:
  - **Familia Arawak**: Es la más extensa territorialmente de Sudamérica. Incluye al **Asháninka** (la lengua amazónica con mayor número de hablantes del Perú: Junín, Pasco, Ucayali), Machiguenga, Yine, Nomatsigenga y Yanesha.
  - **Familia Pano**: Incluye al **Shipibo-Konibo** (segunda lengua amazónica más hablada, cuenca del río Ucayali), Matsés y Kapanawa.
  - **Familia Jíbaro**: Comprende al **Awajún** (o Aguaruna, tercera lengua amazónica más hablada: Amazonas, San Martín, Loreto), Wampis (Huambisa) y Achuar.
  - **Familia Tupi-Guaraní**: Cocama-Cocamilla y Omagua.
  - **Familia Ticuna**: Hablada en la triple frontera con Brasil y Colombia.
  - **Familia Cahuapana**: Shawi y Shiwilu.

#### 3. El Castellano en el Perú (Lengua No Amerindia)
- Lengua materna de más del 80% de la población peruana.
- Presenta tres grandes variedades dialectales geográficas:
  1. **Castellano Ribereño o Costeño**: Hablado en la costa (Lima y ciudades litorales), caracterizado por la entonación neutra, elisión o aspiración de la /s/ final y concordancias gramaticales estándares.
  2. **Castellano Andino**: Hablado en la sierra y por migrantes andinos. Caracterizado por el motoseo (confusión en el timbre de vocales /e/ - /i/ y /o/ - /u/ por transferencia del sistema trivocálico quechua /a, i, u/), uso reiterado de diminutivos (*"aquicito"*, *"casita"*), doble posesivo (*"su casa de mi papá"*) y el verbo al final de la oración (*"Manzana comiendo está"*).
  3. **Castellano Amazónico**: Hablado en la selva. Caracterizado por el cambio de la /f/ por /x/ o /j/ (*"san juan"* por San Juan, *"jue"* por fue), anteposición del genitivo (*"De mi tía su loro"*), y entonación melódica ondulante.

#### 4. Fenómenos Sociolingüísticos: Diglosia e Interculturalidad
- **Bilingüismo**: Situación en la cual un individuo o comunidad domina dos lenguas distintas (ej. castellano y quechua).
- **Diglosia**: Fenómeno de **desigualdad y asimetría sociopolítica** en el que dos lenguas coexisten en un mismo territorio pero una de ellas goza de prestigio social, poder económico y estatus oficial de poder (el castellano: lengua "alta"), mientras que la otra queda marginada a la informalidad doméstica o comunal rural (el quechua o lenguas amazónicas: lengua "baja").
- **Educación Intercultural Bilingüe (EIB)**: Política educativa del Estado que garantiza que los niños indígenas reciban instrucción inicial y primaria en su propia lengua originaria materna, aprendiendo el castellano como segunda lengua.

