### A. Las Variaciones Lingüísticas de la Lengua
Una lengua no es un bloque homogéneo ni estático; presenta variaciones condicionadas por la geografía, el estrato sociocultural y la situación comunicativa:

#### 1. El Dialecto o Variación Diatópica (Variación Geográfica o Regional)
Es la variación regional o geográfica de una misma lengua que experimentan los hablantes que residen en distintas zonas del territorio. Se manifiesta en cinco niveles lingüísticos:
- **Nivel Fonético** (Acento y pronunciación): Diferencias de entonación o fonación.
  - *Ejemplo*: El seseo en el Perú frente a la distinción castellana de /s/ y /\theta/ en España; la aspiración de la /s/ final en la costa (*"loh amigoh"*); el cantado característico arequipeño o de la selva.
- **Nivel Léxico** (Vocabulario): Uso de distintas palabras para designar un mismo referente.
  - *Ejemplo*: En el Perú se dice *"chaval"* (España), *"pibe"* (Argentina), *"chico/churre/chibolo"* (Perú), *"guagua"* (Ecuador/Andes).
- **Nivel Semántico** (Significado): Una misma palabra tiene significados completamente distintos según la región.
  - *Ejemplo*: *"Guagua"* en el Perú y Bolivia significa niño pequeño o bebé; en Cuba y Canarias significa autobús de transporte público.
- **Nivel Morfológico** (Estructura de la palabra y afijos): Variación en la formación de palabras o diminutivos.
  - *Ejemplo*: En el Perú andino: *"ahorita"*, *"aquicito"*, *"cerquita"*; en Venezuela o Colombia: *"ahoritica"*, *"ratico"*.
- **Nivel Sintáctico** (Orden y concordancia en la oración): Construcción de frases peculiares en determinadas zonas.
  - *Ejemplo*: En el castellano amazónico: *"De la María su hijo vino"*; en el castellano andino: *"Su casa de Juan"* o *"Dice que ya se fue pues"*.

#### 2. El Sociolecto o Variación Diastrática (Variación Social)
Variación que experimenta la lengua debido a factores socioeconómicos, nivel de instrucción académica o pertenencia a un grupo social. Se estructura en tres **niveles de la lengua**:
- **Nivel Superestándar**:
  - Uso refinado, culto, literario, científico y filosófico del idioma. Léxico amplio, elegante y figuras retóricas elaboradas (*"Aquel egregio pensador exhala una límpida prosa metafísica"*).
- **Nivel Estándar**:
  - Nivel oficial de corrección idiomática general accesible a la mayoría, que sirve como modelo institucional de cohesión nacional (escuela, medios serios):
    - *Nivel Culto*: Habla formal y cuidada usada en conferencias académicas y textos normativos.
    - *Nivel Coloquial o Familiar*: Uso cotidiano, espontáneo y natural en el ámbito familiar y de amistades con corrección gramatical.
- **Nivel Subestándar**:
  - Modalidad lingüística que vulnera deliberadamente la norma estándar, con pobreza léxica, incorrecciones gramaticales y giros marginales:
    - *Nivel Popular*: Errores morfosintácticos frecuentes (*"Haiga"*, *"nadies"*, *"fuistes"*).
    - *Nivel Vulgar o Replana (Argot marginal)*: Jerga carcelaria o callejera degradada que distorsiona los términos (*"paco"* por policía, *"batería"* por amigo, *"luca"* por sol).

#### 3. El Idiolecto o Variación Diafásica (Registro Lingüístico Individual)
- Uso peculiar, personal y distintivo que cada individuo hace de la lengua según su edad, profesión, género o la situación formal/informal en la que se encuentra.
  - *Por la edad*: El lenguaje infantil (*"hacer tuto"*, *"miau miau"*), el juvenil (*"bro"*, *"estoy en modo chill"*) y el de la tercera edad.
  - *Por la profesión (Tecnolecto)*: El léxico técnico especializado de los médicos (*"cefalea"*, *"edema"*), ingenieros o abogados (*"litisconsorte"*, *"dolo"*).

