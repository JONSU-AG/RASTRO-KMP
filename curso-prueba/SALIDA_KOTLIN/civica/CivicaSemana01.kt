### C. La Convivencia Social y el Sistema de Normas
La vida en sociedad requiere de pautas reguladoras que canalicen la conducta humana, prevengan la anarquía y aseguren el orden pacífico y la justicia.

#### Clasificación Comparativa de las Normas:
1. **Normas Morales**:
   - Pautas de conducta dictadas por la propia conciencia moral individual acerca de lo bueno y lo malo.
   - **Autónomas**: El propio sujeto las asume y se las autoimpone voluntariamente.
   - **Interiores**: Valoran prioritariamente la rectitud de la intención y la voluntad.
   - **Incoercibles**: Nadie puede obligar por la fuerza física a ser moral; su transgresión acarrea como sanción el **remordimiento de conciencia** o la reprobación íntima.
   - **Unilaterales**: Imponen deberes pero no conceden facultades a terceros para exigir su cumplimiento forzoso.
2. **Normas Jurídicas**:
   - Reglas de conducta obligatorias emanadas de los órganos competentes del Estado (Congreso, Ejecutivo, Poder Judicial).
   - **Heterónomas**: Son creadas e impuestas por una autoridad exterior, independientemente de que el ciudadano esté o no de acuerdo con ellas.
   - **Exteriores**: Regulan los actos visibles y conductas manifiestas, sin juzgar los pensamientos íntimos a menos que se exterioricen.
   - **Coercibles**: Ante su desacato, el Estado dispone del uso legítimo de la fuerza pública para imponer su cumplimiento coactivo o aplicar sanciones penales/administrativas (cárcel, multas, embargos).
   - **Bilaterales**: Frente al deber jurídico de un sujeto, existe la facultad o derecho de otro para exigir su cumplimiento efectivo.
3. **Normas Sociales o Convencionales (Usos y Costumbres)**:
   - Reglas de cortesía, decoro, moda, etiqueta y trato social forjadas por la tradición comunitaria.
   - **Heterónomas**, **exteriores** e **incoercibles** por la fuerza estatal; su sanción es el **aislamiento, la censura social, el rechazo o el ridículo** dentro del grupo.
4. **Normas Religiosas**:
   - Preceptos que rigen la relación del ser humano con la divinidad según una fe revelada.
   - **Heterónomas** (emanadas de Dios o de los textos sagrados), interiores y espirituales; su sanción es de orden trascendente (pecado, excomunión, condenación espiritual).



### D. Valores Éticos Fundamentales de la Convivencia Ciudadana
- **Tolerancia y Respeto a la Diversidad**: Actitud cívica activa de reconocimiento y valoración legítima de la pluralidad de ideas, convicciones religiosas, identidades culturales y opciones de vida en el marco de la Constitución.
- **Solidaridad Cívica**: Adhesión y ayuda mutua ante situaciones de vulnerabilidad, desastre natural o necesidad colectiva; orientada a la consecución del **Bien Común**.
- **Justicia y Equidad**: Dar a cada quien lo que le corresponde según el mérito, la necesidad y la ley, corrigiendo desigualdades estructurales.
- **Cultura de Paz**: Conjunto de valores, actitudes y comportamientos que rechazan toda forma de violencia física o verbal, promoviendo el diálogo deliberativo, la mediación y la resolución pacífica de controversias.

