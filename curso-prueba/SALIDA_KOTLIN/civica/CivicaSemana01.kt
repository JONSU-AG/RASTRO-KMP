## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Dignidad Humana**: Cualidad suprema e inmanente a todo ser humano que le confiere un valor intrínseco inalienable que el Estado debe respetar.
2. **Coercibilidad**: Característica de la norma jurídica que faculta al Estado a emplear la fuerza pública coactiva para hacer cumplir su mandato.
3. **Heteronomía**: Cualidad de una norma que es dictada e impuesta por un agente o autoridad exterior a la voluntad del sujeto obligado.
4. **Bilateralidad**: Estructura de la norma jurídica por la cual a la obligación de un sujeto le corresponde el derecho subjetivo de otro a exigir su cumplimiento.
5. **Principio Pro Homine**: Criterio hermenéutico que obliga a interpretar las normas jurídicas siempre de la manera más favorable para la protección de la persona humana.
6. **Concebido**: Ser humano en gestación desde el momento de la fecundación, reconocido por el ordenamiento peruano como sujeto de derecho para todo cuanto le favorece.
7. **Cultura de Paz**: Sistema de valores y acciones institucionales orientadas a prevenir conflictos y resolver divergencias mediante el diálogo, la justicia y la no violencia.
8. **Bien Común**: Conjunto de condiciones sociales, económicas y jurídicas que permiten a todos los miembros de una sociedad alcanzar su pleno desarrollo humano.
9. **Incoercibilidad**: Condición de las normas morales, religiosas y sociales que impide que su cumplimiento sea impuesto coactivamente por el uso de la fuerza física estatal.
10. **Tolerancia Democrática**: Respeto activo a la libertad de pensamiento, creencia y opinión ajena en el marco de la legalidad constitucional.

