## 3. DESARROLLO TEÓRICO RIGUROSO



### A. La Persona Humana: Concepto, Dimensiones y Estatus Constitucional
1. **Definición Filosófica y Jurídica**:
   - La persona humana es un ser bio-psico-socio-espiritual dotado de conciencia, racionalidad, voluntad libre y dignidad inmanente.
   - En el Derecho Civil peruano (Código Civil de 1984, Art. 1°), *"La persona humana es sujeto de derecho desde su nacimiento. La vida humana comienza con la concepción. El concebido es sujeto de derecho para todo cuanto le favorece"*.
2. **Estatus Constitucional Supremo (Constitución de 1993)**:
   - **Artículo 1°**: *"La defensa de la persona humana y el respeto de su dignidad son el fin supremo de la sociedad y del Estado"*.
   - Este precepto consagra el **Principio Pro Homine** o Antropocéntrico: el Estado, las leyes, la economía y las instituciones públicas existen en función de la persona humana, y no a la inversa.
3. **Dimensiones de la Persona**:
   - *Dimensión Biológica*: Sustrato orgánico, integridad física y salud vital.
   - *Dimensión Psicológica*: Vida anímica, cognición, afectividad, identidad y proyectos vitales.
   - *Dimensión Social y Cívica*: Convivencia comunitaria, pertenencia a la polis, ejercicio de ciudadanía y construcción de la cultura.
   - *Dimensión Ética y Espiritual*: Capacidad de autodeterminación moral, libre albedrío, sentido de justicia y autotrascendencia.



### B. La Dignidad Humana: Fuente de Derechos y Deberes
1. **Naturaleza de la Dignidad**:
   - Es el valor intrínseco, inalienable e inviolable que posee todo ser humano por el solo hecho de pertenecer a la especie humana, con independencia de su edad, género, condición socioeconómica, etnia, religión o nacionalidad.
   - La dignidad no se compra, no se enajena, no prescribe y el Estado no la otorga: el Estado **la reconoce y tiene el deber indeclinable de protegerla**.
2. **Articulación de Derechos y Deberes**:
   - La dignidad es el fundamento matriz de todos los **Derechos Fundamentales**.
   - A todo derecho le corresponde un **deber cívico y correlativo**: el respeto recíproco al derecho ajeno, el cumplimiento de la ley legítima y la contribución solidaria al bienestar general de la comunidad.



### D. Valores Éticos Fundamentales de la Convivencia Ciudadana
- **Tolerancia y Respeto a la Diversidad**: Actitud cívica activa de reconocimiento y valoración legítima de la pluralidad de ideas, convicciones religiosas, identidades culturales y opciones de vida en el marco de la Constitución.
- **Solidaridad Cívica**: Adhesión y ayuda mutua ante situaciones de vulnerabilidad, desastre natural o necesidad colectiva; orientada a la consecución del **Bien Común**.
- **Justicia y Equidad**: Dar a cada quien lo que le corresponde según el mérito, la necesidad y la ley, corrigiendo desigualdades estructurales.
- **Cultura de Paz**: Conjunto de valores, actitudes y comportamientos que rechazan toda forma de violencia física o verbal, promoviendo el diálogo deliberativo, la mediación y la resolución pacífica de controversias.

