### Nivel 3: Aplicación / Casuística
**Enunciado**: Un ciudadano observa en el transporte público que una persona de la tercera edad viaja de pie con evidentes dificultades para sostenerse. Aunque el asiento reservado está ocupado legítimamente por otra persona vulnerable, el ciudadano decide no ceder su propio asiento común. Tras bajar del vehículo, experimenta una profunda inquietud interior, vergüenza y remordimiento de conciencia. La norma que ha transgredido dicho ciudadano y el tipo de sanción experimentada son:
