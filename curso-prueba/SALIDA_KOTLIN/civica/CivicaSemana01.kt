## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa Coacción vs. Coercibilidad**:
   - *Coercibilidad*: La **posibilidad jurídica potencial** que tiene el Estado de emplear la fuerza pública si la norma es vulnerada (propiedad permanente de la norma jurídica).
   - *Coacción*: La **aplicación efectiva y material** de la fuerza sobre el infractor cuando este desobedece la ley (ej. el policía que detiene físicamente al prófugo).
2. **Autonomía moral vs. Relativismo moral**:
   - Que la moral sea *autónoma* significa que brota del discernimiento libre de la razón del sujeto, no que cada quien inventa el bien y el mal arbitrariamente a su conveniencia.
3. **El Concebido en el Perú**:
   - En el Perú, según el Código Civil y la Constitución, el concebido es **sujeto de derecho para todo cuanto le favorece**, subordinado al nacimiento para la atribución de derechos patrimoniales definitivos. Si una pregunta afirma que en el Perú el concebido no tiene ningún derecho hasta que cumple un año, es **absolutamente falsa**.

