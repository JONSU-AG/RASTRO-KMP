## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Ciudadanía**: Condición jurídico-política que adquiere un peruano al cumplir 18 años para intervenir en la gestión del Estado.
2. **Sufragio**: Derecho y deber constitucional mediante el cual los ciudadanos expresan su voluntad política en comicios electorales.
3. **Interdicción Civil**: Declaración judicial que priva a una persona del ejercicio directo de sus derechos civiles por incapacidad absoluta de discernimiento.
4. **Inhabilitación Política**: Sanción que priva temporalmente a una persona del derecho de ejercer funciones públicas y participar activamente en elecciones.
5. **Voto Facultativo**: Derecho a sufragar de manera voluntaria sin que su omisión acarree multas ni sanciones administrativas (mayores de 70 años).
6. **Padrón Electoral**: Relación oficial de ciudadanos hábiles elaborada por el RENIEC y fiscalizada por el JNE para sufragar en un proceso comicial.
7. **Identidad Nacional**: Sentimiento de pertenencia colectiva a una comunidad histórica, cultural y política soberana articulada en torno a valores compartidos.
8. **Interculturalidad**: Diálogo horizontal, enriquecedor y respetuoso entre diversas identidades culturales que conviven dentro de una misma nación.
9. **Símbolos Patrios**: Expresiones visuales y sonoras oficiales (Bandera, Escudo, Himno Nacional) consagradas por la Constitución para representar a la República.
10. **Juicio Político**: Procedimiento parlamentario (Arts. 99° y 100° Const.) para investigar y sancionar a altos dignatarios del Estado por infracciones a la Constitución.

