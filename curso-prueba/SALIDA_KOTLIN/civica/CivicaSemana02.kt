### A. Concepto y Adquisición de la Ciudadanía en el Perú
1. **Definición**: Vínculo jurídico-político que une a una persona con el Estado, confiriéndole la plenitud de derechos civiles y políticos para intervenir activamente en los asuntos públicos de la nación.
2. **Requisitos Constitucionales (Artículo 30° de la Constitución)**:
   - *"Son ciudadanos los peruanos mayores de dieciocho años. Para el ejercicio de la ciudadanía se requiere la inscripción electoral"*.
   - Por ende, son tres condiciones concurrentes:
     1. Ser peruano de nacimiento o por naturalización.
     2. Haber cumplido los 18 años de edad.
     3. Estar debidamente inscrito en el Registro Nacional de Identificación y Estado Civil (RENIEC) y contar con el Documento Nacional de Identidad (DNI) electrónico o convencional.



### D. Suspensión del Ejercicio de la Ciudadanía
El **Artículo 33° de la Constitución Política del Perú** establece de manera taxativa y cerrada las tres únicas causales por las cuales se suspende el ejercicio de la ciudadanía y de los derechos políticos:
1. **Por resolución judicial de interdicción**:
   - Declaración judicial dictada respecto a personas que adolecen de incapacidad absoluta de discernimiento o deterioro mental grave que les impide manifestar su voluntad (regulada con el nuevo régimen de apoyos y salvaguardias del Código Civil).
2. **Por sentencia con pena privativa de la libertad**:
   - Condena penal consentida y ejecutoriada que impone reclusión carcelaria efectiva en un establecimiento penitenciario.
3. **Por sentencia con inhabilitación de los derechos políticos**:
   - Sanción penal o condena impuesta por el Poder Judicial o juicio político del Congreso (Art. 100° Const.) que suspende expresamente la facultad de votar, postular o ejercer función pública por un tiempo determinado.
- *Nota Crucial*: La ciudadanía **se suspende temporalmente**, no se pierde definitivamente la nacionalidad de origen. Al extinguirse la pena o revocarse la medida judicial, los derechos ciudadanos se rehabilitan automáticamente.



