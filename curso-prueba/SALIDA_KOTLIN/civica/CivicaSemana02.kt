| **3. Inhabilitación de Derechos Políticos** | Poder Judicial o Congreso (Juicio político).| Impedimento de ejercer cargos públicos, elegir y ser elegido. | Al vencer el plazo fijado en la sentencia judicial o resolución legislativa. |

