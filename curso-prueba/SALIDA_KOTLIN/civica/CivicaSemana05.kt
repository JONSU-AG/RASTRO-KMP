## 3. DESARROLLO TEÓRICO RIGUROSO



### A. Concepto y Principios de la Democracia
1. **Etimología y Definición**:
   - Del griego \delta\tilde{\eta}\mu\mathrm{os} (*demos*, "pueblo") y \kappa\rho\acute{\alpha}\tau\mathrm{os} (*kratos*, "poder, gobierno"): *"El gobierno del pueblo"*.
   - Forma de gobierno y estilo de vida cívica donde el poder político emana originariamente del conjunto de los ciudadanos y se ejerce conforme al Estado Constitucional de Derecho.
2. **Principios Fundamentales de la Democracia**:
   - **Soberanía Popular**: El pueblo es la única fuente legítima del poder político.
   - **Gobierno de la Mayoría con Respeto a las Minorías**: Las decisiones se adoptan por la mayoría aritmética de votos, pero sin conculcar los derechos inalienables de las minorías.
   - **Pluralismo Político e Ideológico**: Libertad irrestricta para la formación y competencia pacífica de múltiples corrientes ideológicas y partidos políticos.
   - **Periodicidad y Alternancia en el Poder**: Los mandatos no son vitalicios; se renuevan mediante elecciones periódicas, libres y transparentes.
   - **Separación e Independencia de Poderes**: Garantía contra la tiranía mediante frenos y contrapesos institucionales.



### B. Modelos de Democracia
- **Democracia Directa**: Los ciudadanos reunidos en asamblea deliberan y deciden directamente sobre las leyes y asuntos públicos sin intermediarios (modelo de la Atenas clásica de Pericles).
- **Democracia Representativa o Indirecta**: Los ciudadanos eligen periódicamente mediante el voto a sus representantes (Presidente, Congresistas, Alcaldes) para que tomen decisiones en su nombre.
- **Democracia Participativa**: Modelo mixto contemporáneo (adoptado por el Perú) que combina la representación política clásica con mecanismos de **participación directa y fiscalización ciudadana** (referéndum, iniciativa legislativa, revocatoria de autoridades).



### C. Los Partidos Políticos en el Perú (Ley N.° 28094)
1. **Definición y Rol**:
   - Son asociaciones de ciudadanos de derecho privado que expresan el pluralismo democrático, concurren a la formación y manifestación de la voluntad popular y son instrumento fundamental para la participación política.
2. **Funciones Clave**:
   - *Canalización*: Traducen demandas sociales en proyectos de ley y políticas públicas.
   - *Reclutamiento y Formación*: Capacitan líderes cívicos para asumir la función gubernamental.
   - *Control y Fiscalización*: Ejercen una oposición constructiva y transparente al gobierno de turno.
3. **Régimen de Financiamiento y Transparencia**:
   - *Financiamiento Público Directo*: Fondos que el Estado otorga anualmente a los partidos con representación en el Congreso para formación, capacitación e investigación.
   - *Financiamiento Público Indirecto*: Franja electoral gratuita en radio y televisión financiada por el Estado durante las campañas electorales.
   - *Financiamiento Privado*: Prohibición absoluta de aportes anónimos, de empresas condenadas por corrupción, o fondos provenientes del narcotráfico, minería ilegal u otras actividades ilícitas (bancarización estricta).
4. **Cancelación de la Inscripción Partidaria**:
   - No participar en elecciones consecutivas.
   - No alcanzar la valla electoral del 5% de votos válidos nacionales ni colocar al menos 5 congresistas en más de un distrito electoral.
   - Atentar contra la democracia mediante conductas que promuevan el terrorismo o la destrucción violenta del orden constitucional.



