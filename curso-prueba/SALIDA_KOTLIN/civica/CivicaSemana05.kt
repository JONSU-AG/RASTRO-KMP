- *Partido Justicia*: 40 000 votos
- *Partido Igualdad*: 20 000 votos

Aplicando el método de la cifra repartidora (D'Hondt), se divide sucesivamente la votación entre 1, 2, 3 y 4:
- Libertad: 60 000 (1°), 30 000 (3°), 20 000, 15 000
- Justicia: 40 000 (2°), 20 000, 13 333, 10 000
- Igualdad: 20 000, 10 000, 6 666, 5 000

Si el 4° cociente más alto es 20 000 (existiendo un empate para el cuarto escaño entre los cocientes de 20 000), la cifra repartidora es 20 000. El número de escaños que le corresponde a los partidos Libertad, Justicia e Igualdad antes del dirimente de empate es, respectivamente:
A) 3, 1 y 0  
B) 2, 1 y 1 (o dirimido según ley)  
C) 4, 0 y 0  
D) 2, 2 y 0  
E) 1, 2 y 1  

- **Resolución**:
  - Al dividir los votos totales entre la Cifra Repartidora (20 000):
    - Libertad: 60\,000 / 20\,000 = 3 escaños asegurados (o 2 fijos y el 3° en disputa).
    - Justicia: 40\,000 / 20\,000 = 2 escaños (o 1 fijo y el 2° en disputa).
    - Igualdad: 20\,000 / 20\,000 = 1 escaño (en disputa).
    - Evaluando los 4 cocientes más altos directos:
      - 1° más alto: 60 000 (Libertad).
      - 2° más alto: 40 000 (Justicia).
      - 3° más alto: 30 000 (Libertad).
      - 4° más alto: 20 000 (Libertad, Justicia o Igualdad compitiendo por sorteo).
    - Por tanto, Libertad tiene como mínimo 2 escaños, Justicia 1 escaño y el cuarto se asigna por cociente a quien desempaten o corresponda (2, 1 y 1).
- **Clave Correcta**: **B**

