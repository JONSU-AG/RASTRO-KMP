## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Democracia Representativa**: Sistema político donde los ciudadanos delegan el poder de decisión pública en gobernantes electos.
2. **Balotaje (Segunda Vuelta)**: Ronda electoral decisoria entre las dos listas más votadas cuando ninguna alcanzó la mayoría absoluta en primera vuelta.
3. **Valla Electoral**: Porcentaje mínimo de votos válidos (5%) que una organización política debe alcanzar para tener derecho a representación parlamentaria.
4. **Cifra Repartidora**: Coeficiente matemático proporcional (D'Hondt) empleado para distribuir bancas legislativas entre listas en competencia.
5. **Voto Preferencial**: Mecanismo optativo que permite al ciudadano modificar el orden de elección de los candidatos dentro de una lista partidaria.
6. **Franja Electoral**: Espacio publicitario gratuito en medios de comunicación radial y televisiva financiado por el Estado para garantizar igualdad de exposición a los partidos.
7. **Padrón Electoral**: Relación oficial consolidada de ciudadanos facultados para ejercer el voto en una elección determinada.
8. **Pluralismo Político**: Reconocimiento y garantía constitucional de la libre concurrencia de diversas ideologías y partidos en la arena pública.
9. **Mandato Imperativo**: Prohibición constitucional que impide que los parlamentarios actúen atados ciegamente a órdenes jurídicas vinculantes de sus electores o partidos.
10. **Democracia Interna**: Procedimiento comicial obligatorio dentro de los partidos políticos para elegir a sus autoridades y candidatos a cargos públicos.

