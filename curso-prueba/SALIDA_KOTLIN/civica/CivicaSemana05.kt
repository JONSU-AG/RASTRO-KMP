## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **Votos Emitidos vs. Votos Válidos**:
   - Votos emitidos = Votos válidos + Votos blancos + Votos nulos/viciados.
   - La presidencia y la valla electoral se calculan **únicamente sobre los votos válidos**. Si el examen dice "50% de los votos emitidos", es una trampa.
2. **Reelección Inmediata en el Perú**:
   - Está **prohibida la reelección inmediata** para: Presidente de la República, Gobernadores Regionales y Alcaldes Provinciales y Distritales.
3. **Segunda Vuelta Regional**:
   - Para ser elegido Gobernador Regional en primera vuelta se requiere un mínimo del **30\% de votos válidos**, a diferencia de la presidencia que exige más del **50\%**.

