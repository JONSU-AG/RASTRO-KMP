### E. Mecanismos Electorales Cruciales en el Perú

#### 1. La Elección Presidencial y el Balotaje (Artículo 111° de la Constitución)
- Para ser elegido Presidente de la República se requiere obtener **más de la mitad de los votos válidos** (es decir, el 50\% + 1 de los votos válidamente emitidos, sin contar votos blancos ni viciados/nulos).
- **Segunda Vuelta Electoral (Balotaje)**:
  - Si ninguna de las candidaturas alcanza la mayoría absoluta en la primera vuelta, se realiza una segunda vuelta electoral entre los **dos candidatos que obtuvieron la más alta votación relativa**.
  - La segunda vuelta debe realizarse dentro de los **treinta (30) días siguientes a la proclamación oficial de los cómputos** de la primera vuelta.

#### 2. La Valla Electoral o Barrera Legal (Umbral Electoral)
- Para que un partido político acceda a la distribución de escaños en el Congreso de la República, debe superar una barrera legal mínima nacional:
  - Obtener al menos el **5\% de los votos válidos a nivel nacional**, O
  - Obtener al menos **5 representantes al Congreso en más de una circunscripción electoral**.
- Las agrupaciones que no alcancen esta valla pierden su inscripción en el Registro de Organizaciones Políticas (ROP) del JNE.

#### 3. El Método de la Cifra Repartidora (Método D'Hondt)
- Es el algoritmo matemático de proporcionalidad utilizado en el Perú para asignar escaños congresales y regidurías municipales entre las listas que superaron la valla electoral:
  1. Se ordenan las listas y sus votos válidos en orden descendente.
  2. La votación de cada lista se divide sucesivamente entre 1, 2, 3, 4, \dots hasta el número total de curules a repartir.
  3. Se ordenan todos los cocientes obtenidos de mayor a menor.
  4. El cociente que ocupa el lugar correspondiente al número total de escaños a elegir constituye la **Cifra Repartidora**.
  5. Se divide la votación total de cada lista entre la Cifra Repartidora; el resultado entero determina el número de escaños que le corresponde a cada partido.

#### 4. El Voto Preferencial Opcional
- El elector puede votar por la lista de su preferencia y, facultativamente, escribir en el casillero correspondiente hasta **dos números** para favorecer a candidatos específicos dentro de esa lista, alterando el orden interno de postulación en la lista cerrada no bloqueada.

