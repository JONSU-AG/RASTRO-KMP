### D. Lucha contra la Corrupción y Ética en la Función Pública
1. **Definición de Corrupción Pública**:
   - El abuso o mal uso del poder público encomendado a una autoridad o funcionario para obtener un beneficio privado o indebido, vulnerando el interés colectivo y la legalidad.
2. **Principales Delitos contra la Administración Pública (Código Penal Peruano)**:
   - **Peculado (Art. 387°)**:
     - El funcionario público que **se apropia o utiliza, para sí o para otro, caudales o efectos del Estado** cuya percepción, administración o custodia le estén confiados por razón de su cargo (ej. desviar fondos de una obra para comprarse un automóvil personal).
   - **Colusión (Art. 384°)**:
     - El funcionario público que, interviniendo en contratos, adquisiciones, licitaciones o subastas del Estado, **se concierta clandestinamente con los interesados privados para defraudar patrimonialmente al Estado**.
   - **Cohecho (El "Soborno" o "Coima")**:
     - *Cohecho Pasivo*: El funcionario público que **acepta o solicita** un donativo, promesa o ventaja para realizar u omitir un acto de su función.
     - *Cohecho Activo*: El ciudadano o particular que **ofrece o entrega** el soborno al funcionario para obtener un favor indebido.
   - **Tráfico de Influencias (Art. 400°)**:
     - El que, invocando o teniendo influencias reales o simuladas, **recibe o hace prometer para sí o para un tercero donativos o ventajas** con el ofrecimiento de interceder ante un funcionario público que esté conociendo un caso judicial o administrativo.
   - **Enriquecimiento Ilícito (Art. 401°)**:
     - El funcionario que incrementa ilícitamente su patrimonio personal durante el ejercicio del cargo de modo ostensible sin poder justificar el origen legal de sus bienes.
3. **La Ley del Código de Ética de la Función Pública (Ley N.° 27815)**:
   - Exige a todos los servidores del Estado regirse por principios rectores:
     - **Probidad**: Conducta intachable de honradez, veracidad y lealtad a la Nación.
     - **Eficiencia**: Optimización de recursos y servicio de calidad al ciudadano.
     - **Transparencia**: Obligación de rendir cuentas públicas (Ley N.° 27806, Ley de Transparencia y Acceso a la Información Pública).
     - **Idoneidad y Neutralidad Política**: Desempeño profesional estricto sin favorecer a partidos políticos en el ejercicio del cargo.

