**Enunciado**: Dos empresas constructoras suscriben un contrato para la edificación de un viaducto incluyendo una cláusula compromisoria según la cual cualquier litigio derivado de la ejecución de la obra será resuelto mediante un **Arbitraje Institucional de Derecho**. Tras surgir un conflicto técnico, el tribunal arbitral debidamente instalado emite un **Laudo Arbitral** ordenando a una de las partes pagar una indemnización compensatoria. Frente a esto, la empresa perdedora interpone una demanda ordinaria ante un juez civil exigiendo que se vuelva a juzgar el caso desde el inicio. Conforme al Decreto Legislativo N.° 1071 (Ley de Arbitraje), el juez debe:
A) Declarar nulo el laudo y abrir un juicio ordinario de veinte años de duración.  
B) Rechazar liminarmente la demanda por improcedente, dado que el Laudo Arbitral es definitivo, inapelable y vinculante, teniendo la misma eficacia y valor de cosa juzgada que una sentencia judicial firme.  
C) Remitir el expediente al Ministerio Público para que determine si hay cohecho pasivo.  
D) Someter la controversia a una asamblea vecinal mediante referéndum distrital.  
E) Solicitar al Presidente de la República que emita un decreto supremo dirimente.  

