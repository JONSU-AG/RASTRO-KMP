## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **Peculado vs. Cohecho**:
   - Si el funcionario **se roba el dinero del presupuesto que él mismo custodiaba** \rightarrow **Peculado**.
   - Si el funcionario **recibe dinero de un transportista o litigante para no ponerle una multa o favorecerlo** \rightarrow **Cohecho Pasivo**.
2. **Mediador vs. Conciliador**:
   - El mediador **NO propone soluciones**, solo modera y acerca a las partes.
   - El conciliador **SÍ está facultado legalmente para proponer alternativas de solución** que las partes pueden aceptar o rechazar.
3. **PBI vs. IDH**:
   - El PBI es una medida puramente cuantitativa de producción monetaria.
   - El IDH incorpora bienestar social: **salud, educación e ingresos**.

