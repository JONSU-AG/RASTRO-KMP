## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Desarrollo Humano**: Enfoque que prioriza la expansión de libertades y capacidades reales de las personas por encima del mero crecimiento económico.
2. **IDH**: Índice de Desarrollo Humano del PNUD compuesto por indicadores de salud, educación y nivel de ingresos.
3. **SINASEC**: Sistema Nacional de Seguridad Ciudadana encargado de articular la prevención y combate del delito en el Perú.
4. **MASC**: Medios Alternativos de Solución de Conflictos que buscan resolver divergencias pacíficamente al margen del proceso judicial ordinario.
5. **Conciliación Extrajudicial**: Procedimiento con intervención de un tercero neutral facultado para proponer fórmulas de arreglo con valor de sentencia.
6. **Laudo Arbitral**: Decisión vinculante y definitiva emitida por un árbitro o tribunal arbitral que pone fin a una controversia con autoridad de cosa juzgada.
7. **Peculado**: Delito cometido por el funcionario que se apropia ilícitamente de los caudales públicos confiados bajo su administración.
8. **Colusión**: Delito consistente en el pacto clandestino y fraudulento entre funcionarios públicos y proveedores privados en licitaciones del Estado.
9. **Cohecho**: Delito de soborno en la función pública, manifestado en solicitar, aceptar (pasivo) u ofrecer y entregar (activo) dádivas indebidas.
10. **Probidad Administrativa**: Principio ético que impone actuar con rectitud, honradez y rechazo a toda ventaja indebida en el servicio público.

