### B. Seguridad Ciudadana y Convivencia Social
1. **Definición de Seguridad Ciudadana**:
   - Condición social de orden democrático en la cual la persona humana puede ejercer plenamente sus libertades y derechos fundamentales libre de las amenazas de la criminalidad, la violencia y el despojo patrimonial.
