### Nivel 2: Intermedio / Comprensión de MASC
**Enunciado**: Dos empresarios en disputa por el cumplimiento de un contrato comercial deciden convocar a un tercero neutral e imparcial para que restablezca los canales de diálogo rotos entre ambos, facilitando la reunión pero sin que dicho tercero tenga la potestad de proponer soluciones ni de imponer fallos obligatorios. El mecanismo alternativo de resolución de conflictos empleado es la:
A) Conciliación extrajudicial  
B) Negociación directa  
C) Mediación  
D) Vía del arbitraje de derecho  
E) Querella penal  

- **Resolución**: En la **Mediación**, el tercero interviniente (mediador) se limita a facilitar la comunicación y el acercamiento entre las partes, sin estar autorizado a formular fórmulas de arreglo (a diferencia del conciliador) ni a resolver la controversia (a diferencia del árbitro).
- **Clave Correcta**: **C**

