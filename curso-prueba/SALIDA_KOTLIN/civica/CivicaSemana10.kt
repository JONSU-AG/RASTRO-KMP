### Nivel 3: Aplicación / Casuística
**Enunciado**: Un tesorero de una municipalidad distrital retira sistemáticamente de las cuentas corrientes ediles la suma de 50 000 soles destinados al programa de vaso de leche, depositándolos en su cuenta bancaria personal para financiar las vacaciones de su familia. El funcionario ha incurrido de manera flagrante en el delito contra la administración pública tipificado como:
