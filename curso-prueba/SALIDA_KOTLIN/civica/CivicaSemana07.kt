### A. Concepto y Tipos de Constitución
1. **Definición**: Es la **Ley Fundamental y Suprema de un Estado**, norma de normas (*Lex Superior*) que establece la organización y límites de los poderes públicos, consagra los derechos fundamentales de las personas y fija el régimen económico y político de la sociedad.
2. **El Poder Constituyente**:
   - Es la potestad originaria y soberana del pueblo para darse una Constitución o refundar el orden jurídico del Estado (ej. Congreso Constituyente Democrático de 1993).
