### B. Estructura de la Constitución Política del Perú de 1993
Aprobada mediante el referéndum del 31 de octubre de 1993 y promulgada el 29 de diciembre de 1993, entrando en vigencia el **1 de enero de 1994**. Consta de un **Preámbulo**, **6 Títulos**, **26 Capítulos**, **206 Artículos**, **16 Disposiciones Finales y Transitorias** y una **Declaración sobre la Antártida**:
