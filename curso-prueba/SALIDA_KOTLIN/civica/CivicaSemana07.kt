### Nemotecnia para las Vías de Reforma Constitucional (Art. 206°):
> **"66 MÁS REFERÉNDUM Ó 87 EN DOS LEGISLATURAS SEGUIDAS"**
- Vía 1: **66 votos** + **Referéndum**.
- Vía 2: **87 votos** en **dos legislaturas sucesivas** (sin referéndum).



### Nemotecnia de los 3 Niveles Clave de la Pirámide:
> **"CON - LE - RE"**
- **CON**: Nivel **Con**stitucional (Constitución)
- **LE**: Nivel **Le**gal (Leyes, Decretos Legislativos, Ordenanzas)
- **RE**: Nivel **Re**glamentario (Decretos Supremos)

