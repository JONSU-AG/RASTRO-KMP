### E. El Procedimiento de Reforma Constitucional (Artículo 206° de la Constitución)
Toda reforma constitucional debe ser aprobada en el Congreso de la República.
1. **Iniciativa de Reforma Constitucional**:
   - El Presidente de la República con aprobación del Consejo de Ministros.
   - El número de congresistas equivalente al menos al 0.3% de la población electoral nacional con firmas válidas comprobadas por el JNE.
2. **Las Dos Vías Legales de Aprobación**:
   - **Vía A (Mayoría Absoluta + Referéndum)**:
     - El proyecto de ley de reforma es aprobado en una legislatura por el Congreso con mayoría absoluta del número legal de congresistas (**al menos 66 votos**), y luego debe ser **ratificado obligatoriamente mediante Referéndum popular**.
   - **Vía B (Doble Votación Calificada sin Referéndum)**:
     - Puede omitirse el referéndum cuando el acuerdo del Congreso se obtiene en **dos legislaturas ordinarias sucesivas con una votación favorable superior a los dos tercios del número legal de congresistas en cada legislatura (mínimo 87 votos en cada una)**.
3. **Regla de Cierre Institucional**:
   - La ley de reforma constitucional aprobada por el Congreso **NO puede ser observada ni vetada por el Presidente de la República**.

