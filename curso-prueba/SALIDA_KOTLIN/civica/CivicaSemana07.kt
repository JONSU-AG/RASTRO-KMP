- **Leyes Orgánicas**: Regulan la estructura y funcionamiento de los poderes del Estado y de los Organismos Autónomos (requieren aprobación de más de la mitad del número legal de congresistas: mínimo 66 votos).
- **Leyes Ordinarias**: Dictadas por el Congreso en materias comunes (requieren mayoría simple de votos).
- **Resoluciones Legislativas**: Actos parlamentarios para asuntos específicos (permisos de viaje al exterior del Presidente, aprobación de tratados).
- **Decretos Legislativos**: Normas dictadas por el Poder Ejecutivo previa delegación expresa de facultades legislativas por el Congreso mediante ley autoritativa (Art. 104°).
- **Decretos de Urgencia (D.U.)**: Medidas extraordinarias en materia económica y financiera dictadas por el Presidente con refrendo ministerial (Art. 118° inc. 19). No pueden contener materia tributaria.
- **Reglamento del Congreso**: Posee fuerza de ley orgánica.
- **Ordenanzas Regionales**: Normas generales dictadas por el Consejo Regional con rango de ley en su jurisdicción territorial.
- **Ordenanzas Municipales**: Normas generales dictadas por el Concejo Municipal con rango de ley en su jurisdicción distrital o provincial.

#### 3. Nivel III: Nivel Reglamentario (Normas Infralegales del Ejecutivo)
- **Decretos Supremos**: Normas de carácter general dictadas por el Presidente de la República con refrendo de uno o más ministros para reglamentar las leyes sin transgredirlas ni desnaturalizarlas.
- **Resoluciones Supremas**: Decisiones de gobierno firmadas por el Presidente y visadas por el ministro respectivo para nombramientos de altos mandos o actos de política pública.

#### 4. Nivel IV: Nivel Resolutivo Sectorial
- **Resoluciones Ministeriales**: Dictadas por los ministros de Estado en sus respectivas carteras.
- **Resoluciones Viceministeriales**: Dictadas por los viceministros.
- **Resoluciones Directorales**: Dictadas por directores generales de ministerios u organismos públicos.

#### 5. Nivel V: Actos Administrativos y de Particulares
- Resoluciones de jefatura, sentencias judiciales con calidad de cosa juzgada, laudos arbitrales, contratos privados entre particulares, convenios colectivos laborales.



### E. El Procedimiento de Reforma Constitucional (Artículo 206° de la Constitución)
Toda reforma constitucional debe ser aprobada en el Congreso de la República.
1. **Iniciativa de Reforma Constitucional**:
   - El Presidente de la República con aprobación del Consejo de Ministros.
   - El número de congresistas equivalente al menos al 0.3% de la población electoral nacional con firmas válidas comprobadas por el JNE.
2. **Las Dos Vías Legales de Aprobación**:
   - **Vía A (Mayoría Absoluta + Referéndum)**:
     - El proyecto de ley de reforma es aprobado en una legislatura por el Congreso con mayoría absoluta del número legal de congresistas (**al menos 66 votos**), y luego debe ser **ratificado obligatoriamente mediante Referéndum popular**.
   - **Vía B (Doble Votación Calificada sin Referéndum)**:
     - Puede omitirse el referéndum cuando el acuerdo del Congreso se obtiene en **dos legislaturas ordinarias sucesivas con una votación favorable superior a los dos tercios del número legal de congresistas en cada legislatura (mínimo 87 votos en cada una)**.
3. **Regla de Cierre Institucional**:
   - La ley de reforma constitucional aprobada por el Congreso **NO puede ser observada ni vetada por el Presidente de la República**.

