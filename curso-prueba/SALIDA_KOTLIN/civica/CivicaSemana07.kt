## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa de las Ordenanzas Municipales y Regionales**:
   - Las ordenanzas municipales y regionales **tienen rango de ley** (Nivel II de la pirámide de Kelsen). Por eso, si violan la Constitución, se les impugna mediante la **Acción de Inconstitucionalidad** ante el TC, y no mediante la Acción Popular.
2. **Decretos de Urgencia y Tributos**:
   - La Constitución **prohíbe tajantemente que los Decretos de Urgencia regulen materia tributaria** (crear, modificar o extinguir impuestos). Si una pregunta dice que el Presidente creó un impuesto nuevo vía D.U., esa norma es inconstitucional.
3. **El Presidente no puede observar la reforma constitucional**:
   - En una ley ordinaria, el Presidente tiene 15 días hábiles para promulgarla u observarla. Pero en las **leyes de reforma constitucional (Art. 206°), el Presidente no tiene facultad de veto ni observación**.

