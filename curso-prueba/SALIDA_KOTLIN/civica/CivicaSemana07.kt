## 4. CUADRO COMPARATIVO: LEY ORGÁNICA VS. LEY ORDINARIA VS. DECRETO DE URGENCIA

| Norma Jurídica | Órgano Emisor | Materia Regulada | Votación / Requisito Exclusivo |
| :--- | :--- | :--- | :--- |
| **Ley Orgánica** | Congreso de la República. | Estructura de poderes del Estado y Organismos Autónomos. | Mayoría absoluta del número legal de congresistas (mínimo **66 votos**). |
| **Ley Ordinaria** | Congreso de la República. | Materias generales civiles, penales, laborales, presupuestales. | Mayoría simple de los congresistas presentes en sala. |
| **Decreto Legislativo**| Poder Ejecutivo (Presidente y gabinete). | Materias delegadas expresamente por el Congreso. | Requiere **Ley Autoritativa previa** del Congreso. |
| **Decreto de Urgencia** | Poder Ejecutivo (Presidente y gabinete). | Extraordinaria en materia **económica y financiera**. | No puede contener materia tributaria; fiscalizado por el Congreso. |

