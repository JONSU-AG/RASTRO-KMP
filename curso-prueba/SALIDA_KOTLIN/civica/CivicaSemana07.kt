## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Constitución**: Ley fundamental de un Estado que define el sistema de derechos y la estructura de los poderes públicos.
2. **Poder Constituyente**: Facultad soberana y fundacional del pueblo para redactar y aprobar una nueva Constitución.
3. **Poder Constituido**: Instituciones y autoridades (Congreso, Ejecutivo, Jueces) creadas y reguladas por la propia Constitución.
4. **Supremacía Constitucional**: Principio jurídico según el cual ninguna ley ni autoridad puede situarse por encima de la Carta Magna.
5. **Control Difuso**: Facultad de los jueces ordinarios para inaplicar normas incompatibles con la Constitución en un litigio específico.
6. **Control Concentrado**: Competencia exclusiva del Tribunal Constitucional para expulsar leyes inconstitucionales del ordenamiento.
7. **Ley Orgánica**: Norma legislativa de rango superior que organiza la estructura institucional de los órganos del Estado.
8. **Decreto de Urgencia**: Norma con rango de ley expedida por el Ejecutivo en situaciones extraordinarias de orden económico-financiero.
9. **Referéndum**: Consulta popular directa mediante la cual los ciudadanos ratifican o rechazan una ley o reforma constitucional.
10. **Bloque de Constitucionalidad**: Conjunto de normas y tratados internacionales que sirven de parámetro para interpretar la Constitución.

