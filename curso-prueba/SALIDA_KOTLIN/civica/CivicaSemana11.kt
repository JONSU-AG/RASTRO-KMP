   - **Requisitos Legales para ser Elegido Representante Estudiantil (Art. 100°)**:
     1. Pertenecer al **Tercio Superior** de rendimiento académico de su carrera.
     2. Haber aprobado al menos **treinta y seis (36) créditos** universitarios.
     3. Ser estudiante regular matriculado en el semestre lectivo.
     4. No tener sentencia judicial condenatoria ejecutoriada por delito doloso.
     5. El cargo de representante estudiantil no es remunerado y dura un período determinado en el estatuto.



