## 3. DESARROLLO TEÓRICO RIGUROSO



### A. Marco Constitucional y Fines de la Universidad (Artículo 18° de la Constitución)
1. **Definición Constitucional**:
   - La universidad es una comunidad académica orientada a la investigación y a la docencia, que brinda una formación humanística, científica y tecnológica con una clara conciencia de nuestro país como realidad multicultural.
2. **Fines Fundamentales de la Universidad (Ley Universitaria N.° 30220, Art. 5°)**:
   - Preservar, acrecentar y transmitir de modo crítico la herencia científica, tecnológica, cultural y artística de la humanidad.
   - Formar profesionales de alta calidad de manera integral y con pleno sentido de responsabilidad social.
   - **Realizar y promover la investigación científica, tecnológica y humanística** como función obligatoria y primordial.
   - Proyectar a la comunidad sus acciones y servicios para promover su cambio y desarrollo socioeconómico.
   - Fomentar la afirmación de los valores democráticos, el estado de derecho y la ética ciudadana.
3. **Gratuidad de la Educación en Universidades Públicas (Artículo 17° y 18° Const.)**:
   - En las universidades públicas, el Estado garantiza la **gratuidad de la enseñanza** para la obtención del grado de bachiller y título profesional.
   - *Condición Legal*: La gratuidad está **supeditada al rendimiento académico satisfactorio** de los estudiantes y a no sobrepasar el tiempo regular de duración de los estudios (la pérdida de gratuidad se aplica a estudiantes que desaprueban reiteradamente asignaturas).



### B. Las Cinco Dimensiones de la Autonomía Universitaria (Artículo 8° de la Ley N.° 30220)
La autonomía es inherente a las universidades y se ejerce de conformidad con la Constitución y las leyes de la República:
1. **Autonomía Normativa**:
   - Capacidad exclusiva para redactar, modificar y aprobar su propio **Estatuto Universitario** y los reglamentos internos que rigen la vida institucional.
2. **Autonomía de Gobierno**:
   - Potestad para elegir democráticamente a sus propias autoridades (Rector, Vicerrectores, Decanos) mediante el voto universal, secreto y obligatorio de docentes y estudiantes, sin interferencia de partidos políticos ni del Poder Ejecutivo.
3. **Autonomía Académica**:
   - Libertad para fijar su marco doctrinario, diseñar planes de estudio, crear carreras profesionales, programas de posgrado (maestrías y doctorados), establecer regímenes de evaluación y conferir grados y títulos a nombre de la Nación.
4. **Autonomía Administrativa**:
   - Facultad para organizar su estructura funcional, contratar y promover a su personal docente y no docente, y gestionar sus servicios internos.
5. **Autonomía Económica**:
   - Competencia para administrar libremente su patrimonio, generar recursos directamente recaudados (RDR) y ejecutar su presupuesto conforme a la Ley General de Presupuesto.



### C. La Inviolabilidad del Recinto Universitario (Artículo 19° de la Ley N.° 30220)
- Los campus y locales universitarios son **inviolables**.
- La Policía Nacional del Perú (PNP) y las Fuerzas Armadas **tienen terminantemente prohibido el ingreso a los recintos universitarios**, salvo en tres excepciones constitucionales taxativas:
  1. Por mandato expreso fundado de **orden judicial escrita**.
  2. En caso de **flagrante delito**.
  3. En situación de **peligro inminente de la vida de las personas o grave catástrofe / calamidad pública**.
- La seguridad interna es responsabilidad directa y exclusiva de la propia universidad a través de su cuerpo de seguridad institucional.



## 5. MNEMOTECNIAS PREUNIVERSITARIAS



### Nemotecnia de las 5 Autonomías Universitarias:
> **"NOR - GO - A - AD - EC"**
- **NOR**: **Nor**mativa (Crea sus propios estatutos)
- **GO**: De **Go**bierno (Elige a sus autoridades sin el Ejecutivo)
- **A**: **A**cadémica (Diseña mallas, grados y títulos)
- **AD**: **Ad**ministrativa (Gestiona su personal)
- **EC**: **Ec**onómica (Administra su patrimonio y rentas)



