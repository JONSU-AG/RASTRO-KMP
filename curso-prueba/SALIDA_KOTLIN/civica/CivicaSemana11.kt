**Enunciado**: Cuando una universidad pública aprueba la creación de un nuevo plan curricular de estudios para la carrera de Ingeniería Biomédica y establece sus propios criterios de evaluación y titulación profesional sin requerir autorización previa de un ministerio del Poder Ejecutivo, está ejerciendo su:
