### E. La Comunidad Universitaria: Estudiantes, Docentes y Graduados
1. **Los Docentes Universitarios (Capítulo VII de la Ley)**:
   - *Categorías de Docentes Ordinarios*:
     - **Profesor Principal**: Requiere título profesional, grado académico de **Doctor**, y haber sido profesor asociado al menos 5 años.
     - **Profesor Asociado**: Requiere título profesional y grado académico de **Maestro** (Magíster).
     - **Profesor Auxiliar**: Requiere título profesional y grado de **Maestro**.
   - *Docentes Extraordinarios*: Eméritos, honorarios, investigadores y visitantes.
   - *Docentes Contratados*: Prestan servicios a plazo determinado.
2. **Los Estudiantes Universitarios y el "Tercio Estudiantil"**:
   - Son estudiantes universitarios quienes han culminado la educación básica y han aprobado el proceso de admisión.
