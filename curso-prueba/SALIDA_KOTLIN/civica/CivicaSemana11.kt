## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Autonomía Universitaria**: Potestad inherente a las universidades para autogobernarse, dictar sus normas, diseñar planes académicos y administrar sus recursos.
2. **Inviolabilidad de Campus**: Garantía constitucional que prohíbe el ingreso de la fuerza pública a los recintos universitarios salvo mandato judicial o flagrancia.
3. **Asamblea Universitaria**: Máximo órgano de gobierno colegiado y deliberativo representativo de docentes, estudiantes y graduados.
4. **Consejo Universitario**: Órgano superior colegiado de gestión ejecutiva y administrativa permanente de la universidad.
5. **Tercio Estudiantil**: Cuota de representación democrática equivalente al 33.3% de los miembros en los órganos colegiados universitarios asignada a estudiantes destacados.
6. **SUNEDU**: Superintendencia Nacional de Educación Superior Universitaria, entidad pública técnica encargada del licenciamiento institucional.
7. **Condiciones Básicas de Calidad (CBC)**: Estándares mínimos e indispensables pedagógicos, de infraestructura y de investigación que toda universidad debe satisfacer para operar.
8. **Licenciamiento Institucional**: Autorización legal expedida por la SUNEDU que acredita que una universidad cumple con las CBC.
9. **Cátedra Universitaria**: Unidad académica y pedagógica orientada a la enseñanza y profundización de una disciplina científica o humanística.
10. **Tercio Superior**: Rango académico que agrupa al 33% de estudiantes de mayor rendimiento y promedio ponderado de calificaciones en una carrera profesional.

