### Nivel 1: Básico / Definición Directa
**Enunciado**: De conformidad con la Ley Universitaria N.° 30220, la máxima autoridad colegiada de gobierno de una universidad pública en el Perú, encargada de aprobar y modificar el Estatuto Universitario y definir las políticas generales institucionales, es:
A) El Consejo Universitario  
B) La Asamblea Universitaria  
C) El Tribunal de Honor Universitario  
D) La Defensoría Universitaria  
E) El Consejo de Coordinación Interfacultades  

- **Resolución**: El artículo 56° de la Ley Universitaria N.° 30220 consagra a la **Asamblea Universitaria** como el máximo órgano colegiado de gobierno de la universidad, representativo de toda la comunidad universitaria.
- **Clave Correcta**: **B**

