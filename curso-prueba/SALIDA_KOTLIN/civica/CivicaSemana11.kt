### Nivel 3: Aplicación / Casuística
**Enunciado**: Un contingente policial fuertemente armado ingresa intempestivamente al campus de la Universidad Nacional de San Agustín (UNSA) rompiendo las rejas del recinto, con el propósito de detener a un dirigente estudiantil que pronunciaba un discurso crítico contra el gobierno de turno en una asamblea pacífica, sin contar los efectivos con una orden judicial ni encontrarse el líder cometiendo delito en flagrancia. Dicha intervención policial constituye una violación flagrante de:
A) El principio de subsidiaridad económica municipal  
B) La inviolabilidad del recinto universitario consagrada en la Constitución y la Ley Universitaria  
C) La competencia exclusiva de la Junta Nacional de Justicia  
D) El quórum reglamentario del Consejo de Facultad  
E) El régimen de licencias de funcionamiento de la SUNEDU  

- **Resolución**: Conforme al Artículo 18° de la Constitución y al Artículo 19° de la Ley N.° 30220, los campus universitarios son inviolables; las fuerzas del orden solo pueden ingresar bajo tres causales taxativas: orden judicial escrita, flagrante delito o peligro inminente de la vida/catástrofe. Allanar el campus sin orden judicial vulnera la **inviolabilidad del recinto universitario**.
- **Clave Correcta**: **B**

