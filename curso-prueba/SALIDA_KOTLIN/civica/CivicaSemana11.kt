B) Inmunidad parlamentaria de cátedra  
C) Autonomía académica  
D) Jurisdicción arbitral descentralizada  
E) Potestad de control concentrado  

- **Resolución**: La **autonomía académica** (Art. 8° inc. 3 de la Ley N.° 30220) faculta a la universidad a determinar su propio marco doctrinario, diseñar planes de estudio e investigación y otorgar los grados académicos y títulos profesionales a nombre de la Nación.
- **Clave Correcta**: **C**

