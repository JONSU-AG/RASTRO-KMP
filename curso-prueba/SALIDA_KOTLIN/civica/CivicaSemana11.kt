### D. Estructura y Órganos de Gobierno de la Universidad (Ley N.° 30220)

#### 1. La Asamblea Universitaria (Máximo Órgano Colegiado de Gobierno)
- Representa a toda la comunidad universitaria y define las políticas generales de la institución.
- **Composición Obligatoria**:
  - El Rector (quien la preside) y los Vicerrectores.
  - Los Decanos de todas las Facultades.
  - Representantes de los Docentes ordinarios (51% de profesores principales, asociados y auxiliares).
  - Representantes de los Estudiantes (**El Tercio Estudiantil: 1/3 del total de miembros de la asamblea**).
  - Representantes de los Graduados en calidad de supernumerarios (al menos el 2%).
- **Atribuciones Principales**:
  - Reformar el Estatuto Universitario.
  - Declarar la revocatoria o vacancia del Rector y Vicerrectores por causales graves.
  - Elegir a los miembros del Comité Electoral Universitario y del Tribunal de Honor.
  - Aprobar la creación, fusión o supresión de Facultades y Escuelas Profesionales.

#### 2. El Consejo Universitario (Órgano de Dirección Superior y Ejecución)
- Órgano colegiado de gestión permanente y ejecutiva de la universidad.
- Integrado por: El Rector, Vicerrectores, un tercio de Decanos, representantes estudiantiles (un tercio del consejo) y un delegado de los graduados.
- Funciones: Dictar el reglamento general, aprobar el presupuesto anual de la universidad, conferir los grados académicos y títulos profesionales aprobados por las Facultades, y autorizar contratos y convenios.

#### 3. El Rectorado
- El **Rector** es la máxima autoridad ejecutiva, personero legal y representante institucional de la universidad pública o privada.
- Acompañado obligatoriamente por dos autoridades electas:
  - **Vicerrector Académico**: Dirige la política pedagógica y curricular.
  - **Vicerrector de Investigación**: Promueve y financia los proyectos de ciencia, patentes y tecnología.
- *Requisitos para ser Rector* (Art. 61°): Ser ciudadano en ejercicio, docente ordinario en la categoría de Principal con más de 12 años de docencia, **poseer el grado de Doctor obtenido con estudios presenciales**, y no haber sido condenado por delito doloso ni destituido por falta grave. Su mandato dura **5 años** y no hay reelección inmediata.

#### 4. El Gobierno de las Facultades
- Las Facultades son las unidades fundamentales de formación académica y profesional.
- **El Decano**: Máxima autoridad ejecutiva de la Facultad. Requisitos: Profesor Principal con grado de Doctor o Maestro en su especialidad. Mandato de **4 años**.
- **El Consejo de Facultad**: Órgano normativo y de dirección de la Facultad, compuesto por el Decano, representantes de los docentes y representantes de los estudiantes (**el tercio estudiantil**).

---



### F. La SUNEDU y el Licenciamiento Institucional
- La **Superintendencia Nacional de Educación Superior Universitaria (SUNEDU)**:
  - Organismo técnico especializado adscrito al Ministerio de Educación creado por la Ley N.° 30220 en reemplazo de la extinta Asamblea Nacional de Rectores (ANR).
  - **Función Primordial: El Licenciamiento Institucional**:
    - Procedimiento administrativo obligatorio que verifica si una universidad (pública o privada) cumple con las **Condiciones Básicas de Calidad (CBC)** para operar legalmente:
      1. Existencia de objetivos académicos y planes de estudio actualizados.
      2. Infraestructura y equipamiento adecuado (laboratorios, bibliotecas, talleres seguros).
      3. Líneas de investigación científica activas y presupuesto asignado.
      4. Al menos el **25% de docentes a tiempo completo**.
      5. Servicios educacionales complementarios (salud, psicopedagogía, deporte, bolsa de trabajo).
      6. Mecanismos de inserción laboral y transparencia financiera.

