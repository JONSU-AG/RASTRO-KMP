## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Estado**: Sociedad humana jurídica y políticamente organizada asentada sobre un territorio determinado con gobierno soberano.
2. **Nación**: Colectividad histórico-cultural cohesionada por lazos de identidad, idioma, tradiciones y autoconciencia de destino común.
3. **Soberanía**: Potestad suprema e independiente de un Estado para autodeterminarse sin sumisión a mandatos exteriores.
4. **Ius Soli**: Principio de atribución de la nacionalidad fundamentado en el lugar o territorio físico de nacimiento.
5. **Ius Sanguinis**: Principio de atribución de la nacionalidad determinado por la filiación biológica o consanguínea de los progenitores.
6. **Dominio Marítimo**: Espacio oceánico de doscientas millas sobre el cual el Estado peruano ejerce soberanía y jurisdicción exclusiva (Mar de Grau).
7. **Inalienabilidad Territorial**: Condición jurídica por la cual el territorio nacional no puede ser vendido, donado ni cedido a terceros.
8. **Derecho de Insurgencia**: Facultad legítima de la población civil para rebelarse pacíficamente y desobedecer a un gobierno de facto o usurpador del orden constitucional.
9. **Estado Unitario**: Modelo estatal donde existe un único centro supremo de poder normativo y soberanía política para toda la República.
10. **Descentralización**: Proceso de desconcentración y transferencia progresiva de competencias y recursos desde el gobierno central hacia los gobiernos regionales y locales.

