## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa Unitario vs. Federal**:
   - El Perú **es un Estado unitario descentralizado**, NO federal. Los gobiernos regionales peruanos no tienen soberanía propia ni parlamentos con leyes federales; solo gozan de autonomía política, económica y administrativa dentro de la ley.
2. **El Dominio Marítimo de 200 millas**:
   - La Constitución peruana denomina a este espacio **"Dominio Marítimo"** (no mar territorial en sentido clásico estricto), consagrando la soberanía y jurisdicción especial sobre el Mar de Grau.
3. **Derecho de Insurgencia (Art. 46°)**:
   - Solo procede **en defensa del orden constitucional** frente a un gobierno usurpador o dictatorial de facto; no ampara el desacato a gobiernos democráticos electos legítimamente por discrepancias políticas o huelgas laborales.

