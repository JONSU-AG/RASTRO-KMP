## 3. DESARROLLO TEÓRICO RIGUROSO



### C. Características del Estado Peruano (Artículo 43° de la Constitución)
El Artículo 43° contiene la fórmula política nuclear de la República del Perú:
- **Democrático**: El poder emana del pueblo y se fundamenta en el respeto irrestricto a los derechos humanos y la alternancia republicana.
- **Social**: El Estado no es un mero gendarme pasivo; interviene para garantizar la justicia distributiva, la salud, la educación pública y la protección de los sectores desfavorecidos.
- **Independiente y Soberano**: No reconoce poder terrenal superior a sí mismo ni se somete a tutelas extranjeras.
- **Uno e Indivisible**: No admite fragmentación territorial ni secesión.
- **Forma de Gobierno**:
  - **Unitario**: Existe un único centro político soberano nacional con validez de la Constitución para todo el país.
  - **Representativo**: Los gobernantes ejercen el poder por delegación del pueblo expresada a través del voto ciudadano.
  - **Descentralizado**: El poder se desconcentra territorialmente en tres niveles de gobierno: Nacional, Regional y Local.
- **Separación de Poderes**: El poder estatal se distribuye en tres ramas clásicas independientes y autónomas: Poder Legislativo, Poder Ejecutivo y Poder Judicial, sometidos a un sistema de pesos y contrapesos (*checks and balances*).



### D. Deberes Primordiales del Estado Peruano (Artículo 44° de la Constitución)
Son obligaciones supremas e inexcusables fijadas por el constituyente:
1. **Defender la soberanía nacional**.
2. **Garantizar la plena vigencia de los derechos humanos**.
3. **Proteger a la población de las amenazas contra su seguridad** (seguridad integral ciudadana y nacional).
4. **Promover el bienestar general** que se fundamenta en la justicia y en el desarrollo integral y equilibrado de la Nación.
5. **Establecer y ejecutar la política de fronteras** y promover la integración, particularmente latinoamericana, así como el desarrollo y la cohesión en las zonas fronterizas.



### E. Legitimidad del Poder y el Derecho de Insurgencia
1. **Origen Popular del Poder (Artículo 45° de la Constitución)**:
   - *"El poder del Estado emana del pueblo. Quienes lo ejercen lo hacen con las limitaciones y responsabilidades que la Constitución y las leyes establecen"*.
   - Ninguna persona, organización, fuerza armada, policía nacional o fracción del pueblo puede atribuirse el ejercicio del poder. Hacerlo constituye **delito de rebelión o sedición**.
2. **El Principio de Resistencia y el Derecho de Insurgencia (Artículo 46° de la Constitución)**:
   - *"Nadie debe obediencia a un gobierno usurpador, ni a quienes asumen funciones públicas en violación de la Constitución y de las leyes"*.
   - *"La población civil tiene el derecho de insurgencia en defensa del orden constitucional"*.
   - Cláusula de cierre republicano: Los actos de quienes usurpan funciones públicas son nulos de pleno derecho.

