### Nivel 4: Análisis Crítico / Modelo DECO - UNSA
**Enunciado**: El Artículo 54° de la Constitución Política del Perú prescribe que el territorio del Estado es inalienable e inviolable, comprendiendo el suelo, el subsuelo, el dominio marítimo y el espacio aéreo que los cubre. A partir de esta premisa, si una empresa transnacional minera adquiere legalmente la propiedad de un predio superficial de 100 hectáreas en los Andes peruanos, se colige válidamente que:
A) La empresa adquiere automáticamente la soberanía territorial y puede fundar una república independiente.  
B) La empresa deviene en dueña soberana absoluta del subsuelo minero y de los yacimientos minerales que yacen debajo de la tierra.  
C) Los recursos minerales del subsuelo continúan siendo patrimonio soberano del Estado peruano, requiriendo la empresa una concesión minera legal para su explotación.  
D) El espacio aéreo sobre el predio deja de pertenecer a la jurisdicción de la Fuerza Aérea del Perú.  
E) Las leyes del Estado peruano quedan suspendidas dentro del predio comercial adquirido.  

- **Resolución**: En la doctrina constitucional peruana (Art. 54° y Art. 66°), el suelo superficial puede ser objeto de propiedad privada, pero los recursos naturales y el subsuelo son inalienables y pertenecen soberanamente al Estado; los particulares solo obtienen el derecho de aprovechamiento económico mediante concesión, manteniéndose la soberanía del Estado.
