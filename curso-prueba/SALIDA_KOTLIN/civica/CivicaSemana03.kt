### A. Distinción Conceptual: Estado vs. Nación
1. **Nación (Concepto Sociológico y Cultural)**:
   - Es una comunidad humana unida por vínculos históricos, culturales, lingüísticos, tradicionales, psicológicos y de autoconciencia colectiva que comparte un pasado común y un proyecto de destino compartido.
   - Una nación **puede existir sin tener un Estado propio territorialmente soberano** (ej. la nación kurda, la nación palestina durante décadas, los pueblos indígenas originarios).
2. **Estado (Concepto Jurídico y Político)**:
   - Es la **sociedad jurídica y políticamente organizada bajo un gobierno común**, asentada sobre un territorio determinado y provista de un poder soberano con monopolio legítimo de la fuerza para dictar y hacer cumplir leyes.
   - Un Estado puede albergar en su seno a múltiples naciones o nacionalidades culturales (**Estados Plurinacionales**, como Bolivia, o Estados pluriculturales como el Perú).



### B. Los Cuatro Elementos Constitutivos del Estado
1. **El Pueblo o Población (Elemento Humano)**:
   - Conjunto de seres humanos que habitan en el territorio y están vinculados jurídicamente al Estado mediante la **nacionalidad**.
   - Criterios de atribución de la nacionalidad (Art. 52° de la Constitución):
     - *Ius Soli* (Derecho de suelo): Son peruanos por nacimiento los nacidos en el territorio de la República.
     - *Ius Sanguinis* (Derecho de sangre): Son peruanos por nacimiento los hijos de padre o madre peruanos nacidos en el exterior, inscritos en el registro respectivo durante su minoría de edad.
     - *Ius Domicilii / Naturalización*: Extranjeros que adquieren la nacionalidad por residencia legal o por matrimonio con un cónyuge peruano.
2. **El Territorio (Elemento Físico o Geográfico - Artículo 54° de la Constitución)**:
   - Es el espacio geográfico tridimensional e inalienable sobre el cual el Estado ejerce soberanía exclusiva y jurisdicción legal.
   - Comprende:
     - **El Suelo**: Superficie continental e insular.
     - **El Subsuelo**: Espacio físico situado bajo el suelo (los recursos mineros e hidrocarburos son patrimonio soberano del Estado; Art. 66°).
     - **El Dominio Marítimo (Mar de Grau)**: Comprende el mar adyacente a sus costas hasta la distancia de **doscientas (200) millas marinas**, ejerciendo soberanía y jurisdicción sobre el lecho y el subsuelo marino.
     - **El Espacio Aéreo**: Espacio que cubre el territorio y el mar adyacente hasta el límite de las doscientas millas.
   - Principio: *"El territorio del Estado es inalienable e inviolable"* (Art. 54°).
3. **El Poder Político o Soberanía (Elemento Formal)**:
   - Capacidad del Estado para autodeterminarse, emitir mandatos jurídicos obligatorios y hacerlos cumplir coactivamente dentro de su territorio (*Soberanía Interna*), y actuar de manera independiente y libre de dominación foránea en el concierto internacional (*Soberanía Externa*).
4. **El Ordenamiento Jurídico**:
   - Sistema jerárquico de leyes, normas y principios encabezado por la Constitución Política que institucionaliza y limita el ejercicio del poder público.



