## 4. CUADRO COMPARATIVO: REVOCATORIA VS. REMOCIÓN DE AUTORIDADES

| Criterio | Revocatoria de Autoridades | Remoción de Autoridades |
| :--- | :--- | :--- |
| **Tipo de Autoridad** | Autoridades elegidas por **voto popular** (Alcaldes, Gobernadores). | Autoridades **designadas** por el gobierno (Prefectos, Directores). |
| **Exclusiones notables**| Presidente de la República y Congresistas (NO se les revoca). | Funcionarios de carrera con estabilidad laboral jurisdiccional. |
| **Porcentaje de Firmas**| **25%** del padrón electoral de la circunscripción. | **Más del 50%** de los electores de la jurisdicción. |
| **Procedimiento** | Consulta en urnas organizada por la ONPE y el JNE. | Acreditación de firmas y destitución administrativa inmediata. |
| **Temporalidad** | Solo en el **tercer año de mandato**. | En cualquier momento del ejercicio del cargo de confianza. |

