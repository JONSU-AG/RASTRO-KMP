## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa de "Revocar Congresistas o al Presidente"**:
   - Muchos postulantes caen en la trampa cuando una alternativa dice: *"Los ciudadanos juntan el 25% de firmas para revocar al Presidente del Congreso"*. En el Perú, **NO existe la revocatoria de congresistas ni del Presidente de la República**; estos solo dejan el cargo por vacancia, disolución constitucional o renuncia.
2. **Revocatoria en el último año**:
   - La revocatoria **está prohibida en el primer y en el último año de gestión municipal o regional** para evitar la parálisis administrativa y el sabotaje electoral. Solo se realiza en el 3er año.
3. **Referéndum y Presupuesto de la República**:
   - El pueblo **no puede derogar vía referéndum la Ley de Presupuesto General de la República** ni la ley del Impuesto General a las Ventas (IGV).

