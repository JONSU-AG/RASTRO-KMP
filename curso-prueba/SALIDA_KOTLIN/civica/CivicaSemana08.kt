### C. Derechos de Control Ciudadano (Fiscalizar y Sancionar)
Son mecanismos mediante los cuales los ciudadanos evalúan la idoneidad y conducta funcional de sus autoridades en ejercicio:

#### 1. La Revocatoria de Autoridades
- Proceso electoral mediante el cual los ciudadanos deciden en las urnas si separan anticipadamente de sus cargos a las **autoridades de elección popular subnacionales**.
- **¿A quiénes SÍ se puede revocar?**:
  - Alcaldes Provinciales y Distritales.
  - Regidores Provinciales y Distritales.
  - Gobernadores Regionales y Vicegobernadores.
  - Consejeros Regionales.
  - Jueces de Paz (provenientes de elección popular).
- **¿A quiénes NO se puede revocar jamás? (TRAMPA CLÁSICA DE ADMISIÓN)**:
  - **Al Presidente de la República**.
  - **A los Congresistas de la República**.
  - **A los magistrados del Poder Judicial ni fiscales nombrados por la JNJ**.
- **Reglas Procedimentales y Cronograma de la Revocatoria (Reforma Ley N.° 30305)**:
  - *Porcentaje de Firmas*: Requiere el respaldo del **25\% de los electores de la circunscripción respectiva**.
  - *Oportunidad*: La consulta de revocatoria solo procede **una sola vez en el tercer año del mandato de cuatro años** (prohibida en el primer y en el último año de gestión).
  - *Quórum de Aprobación*: Para que la autoridad sea revocada se requiere la asistencia de al menos el **50\% de electores hábiles** y que la opción del "SÍ" obtenga la mitad más uno de los votos válidos.
  - *No hay elecciones complementarias*: Los revocados son reemplazados por sus accesitarios o vicegobernadores hasta culminar el período legal original.

#### 2. La Remoción de Autoridades
- Derecho a destituir a autoridades **designadas por el gobierno central o regional** que desempeñan cargos de confianza no electivos (ej. Prefectos, Subprefectos, Directores de UGEL, directores regionales de salud).
- **Requisito legal**: Requiere la adhesión de más del **50\% de los ciudadanos** de la jurisdicción respectiva.

#### 3. La Demanda de Rendición de Cuentas
- Derecho de los ciudadanos a interpelar a las autoridades locales o regionales respecto a la ejecución presupuestal y el uso de los recursos públicos de obras específicas.
- **Requisito legal**: Requiere la firma del **10\% del padrón de electores** con un pliego interpelatorio de preguntas que la autoridad está obligada por ley a responder en audiencia pública.

