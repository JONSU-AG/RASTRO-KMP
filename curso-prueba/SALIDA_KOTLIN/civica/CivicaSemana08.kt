## 5. MNEMOTECNIAS PREUNIVERSITARIAS



### Nemotecnia de las Materias Prohibidas en Referéndum (Art. 32°):
> **"NO CONSULTES: DERECHOS, TRIBUTOS NI TRATADOS"**
- **DERECHOS**: Prohibido disminuir derechos fundamentales.
- **TRIBUTOS**: Prohibido consultar leyes tributarias y presupuestales.
- **TRATADOS**: Prohibido alterar tratados internacionales en vigor.

