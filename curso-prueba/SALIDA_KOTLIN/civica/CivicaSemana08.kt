## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS CÍVICOS
1. **Participación Ciudadana**: Ejercicio directo de los derechos cívicos mediante el cual la población propone normas y toma decisiones públicas.
2. **Control Ciudadano**: Conjunto de mecanismos jurídicos para supervisar, fiscalizar y destituir a autoridades en funciones.
3. **Revocatoria**: Destitución popular en urnas de autoridades subnacionales de elección popular mediante el 25% de firmas en el tercer año.
4. **Remoción**: Cese administrativo de autoridades de confianza no electivas designadas por el gobierno con más del 50% de firmas.
5. **Rendición de Cuentas**: Derecho a interpelar a una autoridad local sobre el destino de los recursos financieros públicos con el 10% de firmas.
6. **Iniciativa Legislativa**: Facultad de los ciudadanos para presentar proyectos de ley al Congreso con el 0.3% del padrón electoral.
7. **Referéndum**: Consulta comicial en la que los electores ratifican o desaprueban una norma constitucional, ley u ordenanza.
8. **Consulta Previa**: Proceso de diálogo institucionalizado con pueblos originarios antes de autorizar proyectos sobre sus territorios ancestrales.
9. **Población Electoral**: Total de ciudadanos inscritos hábilmente en el padrón del RENIEC con derecho a sufragio.
10. **Quórum Electoral**: Porcentaje mínimo de asistencia de votantes o de votos requeridos por la ley para que una consulta comicial sea jurídicamente válida.

