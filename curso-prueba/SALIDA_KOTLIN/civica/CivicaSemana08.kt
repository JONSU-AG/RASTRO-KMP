### B. Derechos de Participación Ciudadana (Proponer y Decidir)
Son facultades mediante las cuales los ciudadanos intervienen en la creación normativa y la toma de decisiones públicas:

#### 1. Iniciativa de Reforma Constitucional
- Derecho ciudadano para proponer enmiendas totales o parciales al texto de la Constitución.
- **Requisito legal**: Requiere el respaldo comprobado de no menos del **0.3\% de la población electoral nacional** con firmas válidas verificadas por el RENIEC y el JNE.

#### 2. Iniciativa en la Formación de Leyes (Iniciativa Legislativa)
- Derecho de los ciudadanos para presentar proyectos de ley ordinaria ante el Congreso de la República.
- **Requisito legal**: Respaldada por el **0.3\% del padrón electoral nacional**. El Congreso tiene la obligación reglamentaria de dictaminar el proyecto en comisiones.

#### 3. Iniciativa en la Formación de Dispositivos Regionales y Locales
- Derecho a presentar proyectos de ordenanzas regionales ante el Consejo Regional o de ordenanzas municipales ante el Concejo Municipal.

#### 4. El Referéndum (Artículo 32° de la Constitución)
Es la consulta popular directa convocada por el JNE mediante la cual el cuerpo electoral se pronuncia aprobando o desaprobando un asunto normativo o político de trascendencia.
- **Materias que SÍ pueden someterse a Referéndum**:
  1. La reforma total o parcial de la Constitución.
  2. La aprobación de leyes, normas regionales de carácter general y ordenanzas municipales.
  3. La desaprobación de leyes, decretos legislativos y decretos de urgencia.
  4. Materias relativas al proceso de descentralización y conformación de regiones.
- **Materias que NO pueden someterse a Referéndum (PROHIBICIONES TAXATIVAS - Art. 32°)**:
  1. **La supresión o la disminución de los derechos fundamentales de la persona**.
  2. **Las normas de carácter tributario y presupuestal**. (No se puede consultar al pueblo si desea eliminar impuestos o el presupuesto del Estado).
  3. **Los tratados internacionales en vigor**.

#### 5. El Derecho a la Consulta Previa (Convenio 169 de la OIT y Ley N.° 29785)
- Derecho de los pueblos indígenas u originarios a ser consultados de forma previa, libre e informada por el Estado sobre medidas legislativas o administrativas que afecten directamente sus derechos colectivos, tierras comunales, recursos naturales o existencia física y cultural.

