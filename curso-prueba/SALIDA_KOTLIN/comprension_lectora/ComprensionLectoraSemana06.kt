### 3.1 La Falacia del Diccionario Aislado en Comprensión Lectora
El error más grave de un postulante en las preguntas de vocabulario en contexto es evocar la primera definición memorizada del diccionario de la RAE:
- Enunciado del texto: *"El científico examinó la **red** neuronal con sumo cuidado"*.
- Si el alumno piensa en una *malla de pescar peces en el mar*, comete un anacronismo semántico fatal.
- En ese contexto biomédico, *red* significa **circuito o entramado interconectado de axones y dendritas**.

#### La Regla de Oro de la Sustitución Salva-Verdad (*Salva Veritate*)
El sinónimo contextual legítimo es aquel que puede insertarse físicamente en el lugar de la palabra original de modo que:
1. La oración conserve exactamente la misma categoría gramatical (sustantivo por sustantivo, verbo por verbo).
2. El valor de verdad y la intención del autor permanezcan 100% inalterables.
3. No se genere ninguna cacofonía ni discordancia con las palabras adyacentes.



