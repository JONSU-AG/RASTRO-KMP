### Ontología de la Semántica Contextual
- **Contexto Lingüístico:** Conjunto de palabras, sintagmas y oraciones que rodean a un término condicionando y actualizando uno solo de sus semas potenciales.
- **Resignificación:** Proceso dinámico por el cual una palabra común adquiere un sentido especializado o metafórico inédito dentro de una teoría científica o corriente literaria.
- **Sema Actualizado:** Rasgo semántico específico que se activa por la presencia de vocablos afines en la misma proposición.
- **Sema Inhibido:** Rasgo semántico habitual del diccionario que queda temporalmente suspendido o anulado por la fuerza del contexto textual.

