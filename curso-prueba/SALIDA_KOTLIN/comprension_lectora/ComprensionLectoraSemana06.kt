### 3.2 Clasificación de los Usos Contextuales en Exámenes de Admisión

#### A. El Vocablo Común con Sentido Técnico-Filosófico
Palabras del habla común que en un texto académico asumen un rigor conceptual elevado:
- *Mundo:* En física cuántica no es el planeta Tierra, sino un *marco de referencia o universo de posibilidades*.
- *Fuerza:* En física newtoniana no es vigor muscular, sino *magnitud vectorial capaz de alterar la cantidad de movimiento*.
- *Crítica:* En Kant no es hablar mal de alguien, sino *examen riguroso de los límites de la razón pura*.

#### B. La Metáfora Conceptual y el Lenguaje Connotativo
Cuando el autor traslada las propiedades de un dominio físico a un dominio abstracto:
- *"El ministro actuó como un dique de contención ante las presiones populares"*.
  - *Dique de contención* en el contexto social significa **freno, barrera u obstáculo moderador** que impidió el desborde de las protestas.

