## 10. GLOSARIO DE TÉRMINOS CLAVE

1. **Vocabulario en Contexto:** Interpretación semántica de un término condicionada por las redes proposicionales del texto.
2. **Denotación:** Significado literal, objetivo y universalmente acordado de una palabra en la comunidad lingüística.
3. **Connotación:** Valores semánticos secundarios, afectivos o metafóricos añadidos por el contexto o la cultura.
4. **Metáfora:** Tropo que consiste en trasladar el sentido recto de las voces a otro figurado en virtud de una analogía.
5. **Tecnicismo:** Vocablo propio del lenguaje especializado de un arte, ciencia, oficio o disciplina académica.
6. **Desambiguación:** Proceso cognitivo de seleccionar la única acepción pertinente de un término polisémico en un enunciado.
7. **Sustitución Salva-Verdad:** Reemplazo de un vocablo por otro sin alterar la verdad proposicional ni la gramática oracional.
8. **Personificación:** Figura retórica que atribuye propiedades o acciones humanas a objetos inanimados o conceptos abstractos.
9. **Anacronismo Semántico:** Error de atribuir a un texto histórico el significado contemporáneo moderno de una palabra.
10. **Acepción:** Cada uno de los significados diferenciados que una palabra ostenta formalmente en el diccionario.

