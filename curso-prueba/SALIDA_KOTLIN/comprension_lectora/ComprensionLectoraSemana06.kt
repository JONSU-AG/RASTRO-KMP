## 11. BANCO DE FLASHCARDS (Q/A)

- **Q: ¿Por qué en un examen de admisión nunca se debe buscar el significado de una palabra de forma aislada?**  
  **A:** Porque el contexto activa unos semas e inhibe otros; una palabra puede significar cosas opuestas según la disciplina del texto.
- **Q: ¿Qué condición obligatoria debe cumplir un sinónimo contextual para ser la clave correcta?**  
  **A:** Debe preservar exactamente la categoría gramatical original y encajar en el hueco sin distorsionar el sentido del autor.
- **Q: Si en un texto de medicina se lee "El cuadro clínico del paciente", ¿qué significa "cuadro"?**  
  **A:** Significa conjunto o espectro de signos, síntomas y manifestaciones patológicas; no es una pintura artística.
- **Q: ¿Qué es una metáfora conceptual?**  
  **A:** La estructuración de un concepto abstracto en términos de una experiencia física tangible (ejemplo: "el tiempo es dinero").
- **Q: ¿Cómo ayuda un conector adversativo a deducir el significado de una palabra desconocida?**  
  **A:** Porque presenta una idea contraria; si comprendes el término conocido después del conector, el término desconocido será su antónimo.

