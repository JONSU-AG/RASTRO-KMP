### Hack 2: Búsqueda del "Antónimo Fantasma" en el Texto
A menudo, dos o tres renglones antes o después de la palabra interrogada, el autor utilizó un conector adversativo (*pero, sin embargo, en contraste con*):
- Si el autor dice: *"Lejos de mostrarse **pusilánime**, el soldado combatió con denuedo..."*.
- El conector *"lejos de"* te avisa que *pusilánime* es exactamente lo opuesto de *combatir con denuedo*. ¡El texto te regala la respuesta en bandeja de plata!

