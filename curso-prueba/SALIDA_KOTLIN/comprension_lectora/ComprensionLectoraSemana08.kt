## 7. ZONA DE TRAMPAS Y DISTRACTORES ("¡PELIGRO EXAMEN!")

> [!WARNING]
> **Trampa 1: Confundir Explicativo con Argumentativo**
> - Si un texto explica cómo se produce la fisión nuclear del uranio-235 desglosando los neutrones y la masa crítica: es **explicativo/expositivo**.
> - Si el texto afirma que construir centrales nucleares en el Perú es un error catastrófico por el peligro sísmico: es **argumentativo**.
> No confundas explicar un mecanismo científico con defender una postura política sobre su uso.

> [!CAUTION]
> **Trampa 2: La Infografía tomada como Adorno Decorativo**
> En textos mixtos de la UNSA y UNMSM, la infografía **NUNCA es un dibujo de relleno**. Contiene datos estadísticos específicos indispensables para resolver al menos una o dos preguntas de la prueba. Ignorar el gráfico es regalar puntos valiosos.

