### Ontología de la Tipología Textual (Adam / Werlich)
- **Secuencia Textual:** Unidad estructural prototípica (narrativa, descriptiva, argumentativa, explicativa, dialógica o instruccional) que conforma el tejido de un texto.
- **Texto Continuo:** Discurso estructurado en oraciones que se agrupan en párrafos sucesivos dentro de una linealidad de lectura convencional.
- **Texto Discontinuo:** Información organizada de forma no secuencial que requiere una lectura transversal y tabulada (tablas, diagramas, mapas, cuadros estadísticos, recibos).
- **Texto Mixto (Formato DECO):** Texto continuo tradicional que incluye adosada una infografía, gráfico o tabla que complementa, ilustra o refuta la prosa.

