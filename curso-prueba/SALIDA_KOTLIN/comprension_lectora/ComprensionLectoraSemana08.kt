## 11. BANCO DE FLASHCARDS (Q/A)

- **Q: ¿Cuál es el rasgo lingüístico dominante en un texto informativo puro?**  
  **A:** La función referencial del lenguaje, los verbos en modo indicativo y la ausencia total de adjetivos emotivos o juicios de valor.
- **Q: ¿Qué diferencia a un texto explicativo de un texto argumentativo?**  
  **A:** El explicativo busca que el lector *comprenda* un mecanismo científico o ley; el argumentativo busca que el lector *adopte una postura* o tesis debatible.
- **Q: ¿Cómo se reconocen de inmediato los textos instructivos?**  
  **A:** Por el uso sistemático de verbos en modo imperativo o infinitivo organizados en pasos o viñetas secuenciales ordenadas.
- **Q: ¿Qué es un texto mixto según el modelo de evaluación DECO?**  
  **A:** Un texto en prosa continua que incluye una infografía o gráfico estadístico cuyos datos deben cruzarse con la lectura para responder.
- **Q: En un texto dialéctico con dos posturas enfrentadas, ¿cuál es la primera tarea del lector?**  
  **A:** Identificar el punto exacto de controversia o discrepancia central que enfrenta a los dos expositores.

