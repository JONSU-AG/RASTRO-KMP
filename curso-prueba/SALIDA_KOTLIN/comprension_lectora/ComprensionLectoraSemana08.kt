### 3.1 Las Cuatro Familias Textuales Fundamentales del Prospecto UNSA

#### A. Texto Informativo
- **Finalidad Primordial:** Transmitir información fáctica, acontecimientos reales o estados de cosas con la mayor objetividad posible.
- **Rasgos Lingüísticos:** Predominio de la función referencial del lenguaje, verbos en modo indicativo, ausencia de adjetivos emotivos o juicios de valor moral del emisor, tercera persona gramatical.
- **Formatos Típicos:** Noticias periodísticas, reportes meteorológicos, memorandos administrativos, crónicas neutras.

#### B. Texto Argumentativo
- **Finalidad Primordial:** Defender una postura (tesis) y convencer o persuadir al receptor mediante razones estructuradas (argumentos), o refutar una doctrina rival.
- **Rasgos Lingüísticos:** Predominio de la función apelativa y expresiva, uso de conectores causales, consecutivos y concesivos (*porque, por lo tanto, aunque*), verbos de opinión (*sostengo, considero, es evidente*).
- **Formatos Típicos:** Ensayos filosóficos, artículos de opinión, editoriales de periódicos, alegatos jurídicos, columnas críticas.

#### C. Texto Explicativo / Expositivo
- **Finalidad Primordial:** Facilitar la comprensión de un fenómeno complejo, desglosando sus causas, leyes, mecanismos biológicos o teorías científicas.
- **Rasgos Lingüísticos:** Empleo de definiciones formales, aposiciones aclaratorias, analogías pedagógicas, conectores explicativos (*es decir, en otras palabras, esto significa que*), tecnicismos unívocos.
- **Formatos Típicos:** Libros de texto universitarios, enciclopedias científicas, artículos de divulgación (*papers* de revistas indexadas).

#### D. Texto Instructivo / Normativo
- **Finalidad Primordial:** Guiar o pautar paso a paso la conducta del receptor para la ejecución de una tarea, el manejo de un artefacto o el acatamiento de una regla.
- **Rasgos Lingüísticos:** Verbos en modo imperativo (*mezcle, conecte, presione*) o en infinitivo (*armar, calentar*), oraciones breves, enumeraciones ordenadas cronológicamente, viñetas.
- **Formatos Típicos:** Manuales de usuario, recetas de cocina, protocolos de bioseguridad en hospitales, leyes y reglamentos de tránsito.



### 3.2 Cuadro Comparativo de Tipologías Textuales

| Tipo de Texto | Intención Principal | Pregunta Clave | Elemento Estructural Rector | Registro Dominante |
| :--- | :--- | :--- | :--- | :--- |
| **Informativo** | Dar a conocer hechos | *¿Qué ocurrió?* | Datos, fechas y protagonistas | Aséptico / Descriptivo |
| **Argumentativo**| Convencer / Persuadir | *¿Qué postura defiende?* | Tesis central y argumentos | Polémico / Reflexivo |
| **Explicativo** | Hacer comprender | *¿Por qué y cómo es así?* | Leyes, conceptos y causas | Pedagógico / Científico |
| **Instructivo** | Ordenar / Pautar acciones | *¿Cómo se realiza la tarea?* | Secuencia lógica de pasos | Imperativo / Prescriptivo |

