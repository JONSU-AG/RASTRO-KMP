## 10. GLOSARIO DE TÉRMINOS CLAVE

1. **Tipología Textual:** Clasificación analítica de los textos según su propósito, formato y estructura interna.
2. **Texto Continuo:** Discurso en prosa estructurado mediante oraciones integradas en párrafos lineales.
3. **Texto Discontinuo:** Discurso organizado en matrices no secuenciales como infografías, gráficos y esquemas.
4. **Texto Mixto:** Discurso compuesto que articula párrafos continuos junto a elementos gráficos discontinuos.
5. **Texto Informativo:** Escrito enfocado en transmitir hechos reales con neutralidad referencial y objetividad.
6. **Texto Argumentativo:** Escrito estructurado para persuadir o convencer a través de una tesis y argumentos.
7. **Texto Explicativo:** Discurso didáctico orientado a hacer comprender las leyes y causas de un fenómeno complejo.
8. **Texto Instructivo:** Discurso prescriptivo estructurado en secuencias imperativas para guiar acciones prácticas.
9. **Texto Dialéctico:** Confrontación discursiva articulada en torno a dos o más posturas antagónicas sobre un dilema.
10. **Externalidad Social:** En economía y derecho, impacto indirecto positivo o negativo que una acción individual produce sobre terceros.

