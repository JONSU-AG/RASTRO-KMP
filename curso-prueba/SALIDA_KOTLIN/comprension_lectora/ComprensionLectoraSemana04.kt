## 3. DESARROLLO TEÓRICO FORMAL



### 3.1 El Propósito Comunicativo y su Formulación Canónica
En los exámenes de admisión de la UNSA, UNMSM y UNI, las preguntas de propósito comienzan **invariablemente con un verbo en infinitivo**:

| Verbo Infinitivo de Admisión | Cuando el Texto es... | Rasgo Característico del Fragmento |
| :--- | :--- | :--- |
| **Informar / Exponer** | Texto descriptivo o expositivo neutro. | Datos estadísticos, definiciones objetivas, ausencia de adjetivos emotivos. |
| **Persuadir / Convencer** | Ensayo de opinión o columna periodística. | Presenta una tesis y busca que el lector adopte su postura. |
| **Refutar / Impugnar** | Texto dialéctico o polémico. | Ataca directamente las premisas o conclusiones de un autor rival. |
| **Denunciar / Cuestionar** | Artículo de crítica social o política. | Pone al descubierto abusos, irregularidades, corrupción o injusticias. |
| **Concientizar / Alertar** | Texto sobre ecología, salud o educación. | Advierte de peligros inminentes e invita a la prevención activa. |
| **Homenajear / Ensalzar** | Semblanza biográfica o panegírico. | Exalta las virtudes, hazañas o aportes de un personaje célebre. |



### 3.3 El Deslinde entre Hecho, Opinión y Punto de Vista
1. **Hecho:** Suceso fáctico comprobable empíricamente por cualquier observador neutral (*"Arequipa se ubica a 2325 m s. n. m."*).
2. **Opinión:** Juicio subjetivo o estimación personal del autor que admite discrepancia (*"Arequipa posee el clima más agradable de la cordillera andina"*).
3. **Punto de Vista:** La postura articulada donde el autor selecciona determinados hechos para fundamentar su opinión de manera sistemática.

