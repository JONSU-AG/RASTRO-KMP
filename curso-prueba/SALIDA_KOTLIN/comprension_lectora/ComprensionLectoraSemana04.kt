## 10. GLOSARIO DE TÉRMINOS CLAVE

1. **Intención Comunicativa:** Objetivo global o propósito de acción que persigue un autor al producir un texto.
2. **Tono del Texto:** Modulación anímica y actitudinal que impregna las proposiciones del emisor.
3. **Punto de Vista:** Posición conceptual, ideológica o axiológica desde la cual el autor enfoca la materia tratada.
4. **Tono Cáustico / Mordaz:** Actitud discursiva caracterizada por una ironía agresiva, mordaz y demoledora.
5. **Tono Panegírico:** Registro expresivo dedicado al encomio, elogio y exaltación de una persona, doctrina o gesta.
6. **Tono Elegíaco:** Modalidad textual dominada por el lamento, la tristeza, el dolor de la pérdida o la nostalgia.
7. **Tono Escéptico:** Postura de duda metodológica, cautela crítica y suspensión del juicio ante afirmaciones no probadas.
8. **Subjetivema:** Elemento léxico que transparenta el juicio de valor emocional o moral del hablante.
9. **Hecho:** Fenómeno constatable objetivamente en la realidad material independiente de las filias del observador.
10. **Juicio de Valor:** Calificación subjetiva (bueno, malo, abominable, sublime) impuesta a un hecho u objeto.

---



### Matriz de Indicadores de Logro Evaluados
1. **Identificación de la intención comunicativa:** Descubrir el objetivo pragmático final que persigue el autor al emitir su discurso (persuadir, advertir, denunciar, informar, conmover).
2. **Determinación del propósito principal:** Formular mediante un verbo infinitivo (*demostrar, refutar, concientizar, criticar*) la meta rectora del escrito.
3. **Reconocimiento del punto de vista o postura:** Desentrañar la posición ideológica, axiológica o científica desde la cual el autor aborda la problemática.
4. **Análisis del tono del texto:** Calificar con exactitud la actitud anímica predominante del emisor a través de sus elecciones adjetivales y recursos retóricos (irónico, escéptico, solemne, mordaz, panegírico, reivindicativo).

