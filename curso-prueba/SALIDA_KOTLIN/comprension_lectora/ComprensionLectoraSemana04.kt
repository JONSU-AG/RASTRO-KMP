## 11. BANCO DE FLASHCARDS (Q/A)

- **Q: ¿Con qué tipo de verbo debe formularse siempre el propósito central de un texto?**  
  **A:** Con un verbo en infinitivo que exprese una acción comunicativa rectora (demostrar, refutar, concientizar, advertir).
- **Q: ¿Cómo se identifica el tono escéptico en un autor de ciencias?**  
  **A:** Por la presencia de adverbios de duda (quizás, probablemente), exigencia de mayor evidencia empírica y rechazo a conclusiones apresuradas.
- **Q: ¿Qué diferencia existe entre un texto que busca "informar" y uno que busca "persuadir"?**  
  **A:** El informativo transmite datos de manera neutral y aséptica; el persuasivo defiende una tesis para convencer al receptor de adoptar su postura.
- **Q: ¿Por qué la ironía y el sarcasmo exigen un análisis pragmático y no meramente literal?**  
  **A:** Porque en el sarcasmo las palabras dicen literalmente una cosa (ejemplo: un elogio), pero el contexto comunica exactamente lo contrario (una crítica mordaz).
- **Q: Si un texto expone los horrores de una guerra y condena la muerte de civiles inocentes, ¿cuál es su tono dominante?**  
  **A:** Un tono indignado, conmovido, crítico o elegíaco frente a la tragedia humana.

