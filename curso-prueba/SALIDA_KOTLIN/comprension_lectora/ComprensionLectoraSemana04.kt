## 7. ZONA DE TRAMPAS Y DISTRACTORES ("¡PELIGRO EXAMEN!")

> [!WARNING]
> **Trampa 1: Confundir el Tono del Personaje Citado con el Tono del Autor**
> En un texto ensayístico, el autor puede citar a un político enfurecido que lanza insultos:
> - Párrafo 2: *El líder gritó: "¡Son unos traidores miserables que merecen la horca!"*.
> - Si la pregunta pide el tono del autor del texto, **¡NO marques tono insultante ni agresivo!** El autor quizás citó esa frase para analizar con frialdad científica la polarización discursiva. El tono del autor puede ser perfectamente sereno y reflexivo.

> [!CAUTION]
> **Trampa 2: El Propósito Secundario tomado como Propósito Principal**
> Si el autor dedica el 90% de su ensayo a denunciar la corrupción en los contratos de infraestructura y en las dos últimas líneas dice: *"esperemos que el nuevo ministro cambie esto"*, el propósito principal es **denunciar la corrupción**, NO *"felicitar o confiar en el nuevo ministro"*.

