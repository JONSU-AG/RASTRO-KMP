### Ontología de la Macroestructura Textual (Teun van Dijk)
- **Tema:** El objeto o fenómeno general del cual se habla; es el eje vertebrador abstracto expresado canónicamente mediante una frase nominal (*"El sillar de Arequipa"*).
- **Idea Principal (Macroproposición Central):** La afirmación o negación categórica más importante que gobierna el texto. Si se suprime, el texto se desintegra semánticamente.
- **Ideas Secundarias:** Enunciados periféricos dependientes cuya misión es alimentar, demostrar, matizar o ejemplificar a la idea principal.
- **Macrorreglas de Van Dijk:**
  1. *Supresión:* Eliminar la información trivial o redundante.
  2. *Generalización:* Reemplazar una serie de conceptos particulares por su hiperónimo común.
  3. *Construcción:* Reemplazar una secuencia de acciones por la proposición global que las engloba.

