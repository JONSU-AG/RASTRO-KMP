## 5. MNEMOTECNIAS DE COMBATE PREUNIVERSITARIO



### Mnemotecnia 1: "El Triángulo del Texto" (\text{T-I-T})
- **T**ema = El Sujeto de la película (¿Quién es el protagonista?).
- **I**dea Principal = El Argumento de la película (¿Qué hizo o qué le pasó al protagonista?).
- **T**ítulo = El Cartel del Cine (¿Cómo se llama la película en la cartelera?).



### Mnemotecnia 2: "La Balanza del Título"
- Si el título es **demasiado gordo** (muy amplio: *"La Ciencia Moderna"*), aplasta al texto.
- Si el título es **demasiado flaco** (muy estrecho: *"El telescopio de Galileo en 1609"*), deja fuera el 90% del texto.
- El título ganador es el que encaja con la **talla exacta** del texto (*"El impacto astronómico del telescopio de Galileo"*).

