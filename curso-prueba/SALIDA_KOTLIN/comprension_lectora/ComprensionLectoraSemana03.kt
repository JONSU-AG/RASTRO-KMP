## 11. BANCO DE FLASHCARDS (Q/A)

- **Q: ¿Qué diferencia formal existe entre el Tema y la Idea Principal?**  
  **A:** El Tema es un sintagma nominal sin verbo conjugado ("El cambio climático"); la Idea Principal es una oración completa con verbo conjugado ("El cambio climático amenaza la producción agraria").
- **Q: ¿Cómo se comprueba que una oración es la auténtica Idea Principal del texto?**  
  **A:** Aplicando la prueba de supresión: si al quitarla mentalmente el texto queda descabezado y pierde coherencia vertebral, es la idea principal.
- **Q: ¿Qué define a un texto de estructura encuadrada?**  
  **A:** Que la idea principal aparece al comienzo del párrafo y vuelve a ser reformulada o confirmada en la última oración a modo de colofón.
- **Q: ¿Por qué en un texto paralelo la idea principal no se puede subrayar literalmente?**  
  **A:** Porque la idea principal está dispersa de forma implícita entre oraciones equipolentes de igual jerarquía, debiendo ser sintetizada por el lector.
- **Q: ¿Qué características debe tener el mejor título de un texto en el examen de admisión?**  
  **A:** Debe ser breve, carecer de verbo conjugado principal, abarcar con precisión el tema tratado e incluir el enfoque específico del autor.

