## 10. GLOSARIO DE TÉRMINOS CLAVE

1. **Comprensión Global:** Habilidad de aprehender la estructura semántica total de un texto sin perderse en detalles accesorios.
2. **Tema Central:** Frase nominal que engloba el asunto primordial tratado a lo largo de todo el discurso.
3. **Idea Principal:** Oración medular que contiene el mensaje central afirmativo o negativo formulado por el autor.
4. **Idea Secundaria:** Proposición complementaria que ilustra, amplía, fundamenta o deriva de la idea principal.
5. **Texto Analizante:** Estructura en la que la idea principal se ubica en el inicio del párrafo y se desglosa deductivamente.
6. **Texto Sintetizante:** Estructura inductiva que presenta premisas particulares previas y cierra con la idea principal como conclusión.
7. **Texto Encuadrado:** Estructura que enuncia la idea matriz al principio y la retoma al final en forma de resumen o colofón.
8. **Texto Paralelo:** Estructura donde todas las proposiciones poseen el mismo nivel jerárquico y la idea principal es implícita.
9. **Macroestructura:** Contenido semántico global que representa el sentido unificado del texto según Teun van Dijk.
10. **Prueba de Supresión:** Método heurístico para verificar la idea principal eliminándola mentalmente y comprobando el colapso del texto.

