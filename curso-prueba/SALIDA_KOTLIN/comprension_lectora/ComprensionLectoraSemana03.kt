## 7. ZONA DE TRAMPAS Y DISTRACTORES ("¡PELIGRO EXAMEN!")

> [!WARNING]
> **Trampa 1: Marcar una Idea Secundaria como Idea Principal por ser Verdadera**
> En un texto sobre la teoría de la evolución de Darwin:
> - Párrafo 3: *"Darwin viajó en el bergantín HMS Beagle durante cinco años recopilando fósiles en las islas Galápagos"*.
> - La opción B dice: *"Darwin navegó en el HMS Beagle recolectando especies en las Galápagos"*.
> - ¡Es una afirmación 100% verdadera según el texto! Pero **NO es la idea principal**; es un simple dato biográfico secundario que sirve de anécdota. Marcarla es el error más recurrente de los postulantes.

> [!CAUTION]
> **Trampa 2: El Título con Verbo Conjugado**
> Recuerda la regla morfosintáctica inquebrantable de la lengua castellana y los cánones de admisión: **El título es un sintagma nominal, NO una oración**. Si una opción tiene un verbo conjugado principal (*"El calentamiento global destruye la Amazonía"*), suele ser la formulación de la Idea Principal, no el formato canónico del título (*"El calentamiento global y la devastación amazónica"*).

