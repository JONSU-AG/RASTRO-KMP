## 11. BANCO DE FLASHCARDS (Q/A)

- **Q: ¿Qué diferencia medular existe entre una pregunta de comprensión literal y una inferencial?**  
  **A:** La literal evalúa lo que está dicho expresamente en el texto; la inferencial evalúa deducciones lógicas de lo no dicho.
- **Q: Si una alternativa contiene una verdad científica comprobada pero que no figura en el texto, ¿puede ser la clave literal?**  
  **A:** Jamás; en comprensión literal la única verdad válida para la prueba es la información contenida dentro de los límites del texto.
- **Q: ¿En qué consiste la técnica del scanning?**  
  **A:** En desplazar la mirada velozmente sobre el párrafo buscando una palabra clave específica (nombre, número, fecha) sin leer todas las oraciones.
- **Q: ¿Por qué los cuantificadores "siempre", "nunca" o "todos" suelen señalar alternativas distractoras falsas?**  
  **A:** Porque generalizan de forma abusiva asertos que en el texto original están acotados por condiciones particulares o relativas ("a veces", "algunos").
- **Q: ¿Cómo se valida una paráfrasis literal en el examen?**  
  **A:** Comprobando que conserve la misma verdad proposicional y el mismo sujeto de la acción mediante el empleo de sinónimos contextuales.

