## 7. ZONA DE TRAMPAS Y DISTRACTORES ("¡PELIGRO EXAMEN!")

> [!WARNING]
> **Trampa 1: El Conocimiento Previo del Postulante**
> Si el texto dice: *"El lago Titicaca se encuentra ubicado en el altiplano de la meseta del Collao a 2000 metros sobre el nivel del mar"*.
> - Si la pregunta pide: *"Según el texto, ¿a qué altitud se ubica el lago?"*.
> - Tu cerebro sabe que geográficamente está a 3812 m s. n. m.
> - **¡PELIGRO!** Si marcas 3812 m, desapruebas. La pregunta dice *"según el texto"*, y el texto escribió erróneamente 2000 m. En comprensión literal, el texto es la única ley absoluta.

> [!CAUTION]
> **Trampa 2: La Alternativa Verdadera en el Mundo pero Ausente en el Texto**
> Muchas opciones presentan afirmaciones científicas o históricas 100% verdaderas en la vida real, pero que **jamás fueron mencionadas por el autor en el fragmento leído**. En comprensión literal, lo no dicho es inexistente.

