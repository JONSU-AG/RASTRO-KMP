## 3. DESARROLLO TEÓRICO FORMAL



### 3.1 La Naturaleza de la Pregunta Literal en Exámenes de Admisión
En los exámenes de la UNSA, UNMSM y UNI, la comprensión literal **no es una simple copia mecánica** de palabras; evalúa si el postulante distingue entre lo que el texto dice efectivamente y lo que su propia mente cree haber leído.

#### Tipología de Preguntas Literales
1. **Literal Textual (Copia casi idéntica):**
   - Formulación típica: *"Según el texto, el descubrimiento del sillar ocurrió en..."*, *"En el segundo párrafo, el autor afirma expresamente que..."*.
2. **Literal por Paráfrasis:**
   - La respuesta correcta expresa exactamente la misma proposición mediante el uso de sinónimos contextuales y transformaciones sintácticas (ejemplo: cambiar de voz activa a voz pasiva):
   - *Texto:* *"El terremoto de 1868 destruyó las torres de la catedral de Arequipa"*.
   - *Paráfrasis literal clave:* *"Las estructuras campanarias del templo mayor de la Ciudad Blanca fueron derribadas por el sismo decimonónico"*.



### 3.2 El Control de Referencias Anafóricas y Catafóricas
Para no errar en preguntas sobre detalles literales, es obligatorio desatar correctamente los nudos de cohesión gramatical:
- **Anáfora:** *"La bacteria Helicobacter pylori coloniza la mucosa gástrica; **esta** resiste el ácido clorhídrico..."*
  - Pregunta de examen: *¿A qué se refiere la palabra "esta"?*
  - Rastreo literal: Se refiere de forma directa a la bacteria *Helicobacter pylori*, no a la mucosa ni al ácido.
- **Elipsis:** Supresión calculada del sujeto ya mencionado para evitar redundancias. El lector debe reponer mentalmente el sujeto elidido para no atribuir la acción a un personaje equivocado.

