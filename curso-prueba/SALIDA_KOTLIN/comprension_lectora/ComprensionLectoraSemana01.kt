## 10. GLOSARIO DE TÉRMINOS CLAVE

1. **Comprensión Literal:** Nivel básico primario de la lectura enfocado en decodificar y recuperar la información explícita del texto.
2. **Información Explícita:** Aquella que está expresada de forma clara, directa y visible en las palabras escritas.
3. **Paráfrasis:** Explicación o recreación de un texto con palabras propias conservando fielmente el sentido del original.
4. **Scanning (Escaneo):** Lectura rápida exploratoria en zigzag para cazar datos específicos (fechas, nombres, cantidades).
5. **Skimming (Barrido):** Lectura veloz orientada a captar la idea global o arquitectura general del escrito.
6. **Anáfora:** Figura gramatical de referencia donde un pronombre remite a un elemento antecedente ya mencionado.
7. **Elipsis:** Omisión voluntaria de un elemento sintáctico deducible por el contexto previo sin pérdida de claridad.
8. **Cuantificador:** Palabra gramatical (*todos, algunos, ninguno, siempre*) que fija el alcance extensional de una afirmación.
9. **Detalle Fáctico:** Acontecimiento comprobable o dato numérico empírico expuesto en el relato informativo.
10. **Fidelidad Textual:** Cualidad de una interpretación que se ciñe con rigor a los límites semánticos de lo escrito por el autor.

