## 5. MNEMOTECNIAS DE COMBATE PREUNIVERSITARIO



### Mnemotecnia 1: "La Cámara Fotográfica" (\text{F-O-T-O})
Para responder preguntas del nivel literal:
- **F**áctico: Solo lo que ocurrió en el texto.
- **O**bjetivo: Cero suposiciones o deducciones tuyas.
- **T**extual: Encuentra la línea exacta donde está escrito.
- **O**bservable: Si un juez te pidiera la prueba, debes poder subrayarla con resaltador en la hoja.



### Mnemotecnia 2: "El Semáforo de la Paráfrasis"
- 🟢 **Verde (Clave segura):** Dice lo mismo con sinónimos precisos.
- 🟡 **Amarillo (Cuidado):** Dice algo parecido pero cambia un adjetivo (*muchos* por *todos*).
- 🔴 **Rojo (Veneno):** Es una conclusión filosófica que no está escrita en el papel.

