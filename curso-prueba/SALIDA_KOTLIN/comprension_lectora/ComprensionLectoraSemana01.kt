### Matriz de Indicadores de Logro Evaluados
1. **Localización de información explícita:** Ubicar de forma rápida y certera datos puntuales, nombres propios, cronologías y magnitudes numéricas dentro del cuerpo textual.
2. **Reconocimiento de detalles y hechos:** Discriminar las acciones fácticas principales de los sucesos secundarios accesorios descritos por el autor.
3. **Identificación de referencias directas:** Reconocer el antecedente inmediato de pronombres personales, demostrativos y relativos explícitamente fijados en las líneas del texto.
4. **Validación por paráfrasis fiel:** Cotejar si una alternativa reproduce con exactitud conceptual lo expresado literalmente por el texto utilizando una vestimenta léxica sinónima.

