### Ontología de la Lectura Literal
- **Información Explícita:** Contenido textual manifiesto, formulado expresamente mediante signos lingüísticos visibles en el texto.
- **Paráfrasis Fiel:** Traducción o reformulación intralingüística de un enunciado que preserva el 100% de la carga proposicional sin añadir ni suprimir semas esenciales.
- **Rastreo Textual (*Scanning*):** Técnica de barrido visual veloz orientada a localizar una palabra clave (*keyword*), cifra o término unívoco en el soporte impreso.
- **Pregunta de Retención / Memoria:** Ítem de evaluación que mide la capacidad del postulante de rescatar datos objetivos sin recurrir a la especulación subjetiva.

