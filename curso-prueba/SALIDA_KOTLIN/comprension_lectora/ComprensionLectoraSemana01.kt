## 6. TÉCNICAS Y ARTIFICIOS DE CÁLCULO (HACKING PREUNIVERSITARIO)



### Hack 1: La Regla del "Dedo en el Papel" (El Anclaje Dactilar)
Jamás marques una clave literal sin antes colocar literalmente la punta de tu lápiz o dedo sobre la línea del texto donde está la respuesta. Si tu dedo no puede señalar físicamente la frase en el párrafo, **no es una respuesta literal, es una trampa inductiva**.



### Hack 2: Desactivación de Cuantificadores Absolutos
En las alternativas de preguntas literales:
- Si el texto dice: *"En **algunas** regiones andinas llueve con granizo"*.
- Las opciones que contengan: *"En **todas** las regiones"*, *"Invariablemente"*, *"Nunca"* o *"Siempre"* son **distractores falsos por alteración del cuantificador**. Táchalas en un segundo.

