### A. El Problema del Ser (Problema Ontológico)
1. **La pregunta cardinal**: ¿Qué es la realidad última? ¿Cuál es el *arché* o principio de todas las cosas?
2. **Según la Cantidad de Principios**:
   - **Monismo**: Existe una única sustancia o principio que explica todo lo real (Tales: agua; Parménides: el Ser; Spinoza: *Deus sive Natura*; Marx: la materia en movimiento dialéctico).
   - **Dualismo**: Existen dos principios irreductibles (Descartes: *res cogitans* y *res extensa*; Anaxágoras: semillas y *Nous*).
   - **Pluralismo**: Múltiples principios originarios (Empédocles: cuatro elementos; Demócrito: átomos infinitos).
3. **Según la Calidad o Naturaleza del Ser**:
   - **Materialismo**: La materia es primaria, increada y anterior a la conciencia; la conciencia es un producto o propiedad altamente organizada de la materia.
   - **Idealismo**: La idea, el espíritu o la conciencia es primaria; el mundo material sensible es derivado, reflejo o manifestación de lo espiritual.
     - *Idealismo Objetivo*: La idea existe de manera independiente y trascendente al sujeto humano (Platón: Topos Uranos; Hegel: la Idea Absoluta).
     - *Idealismo Subjetivo*: Las cosas solo existen en tanto son percibidas por una mente individual humana (George Berkeley: *Esse est percipi* - "ser es ser percibido").



### D. El Problema del Valor (Problema Axiológico)
- ¿Tienen las cosas valor porque las deseamos, o las deseamos porque tienen valor?
  - **Subjetivismo Axiológico**: El valor depende de la vivencia afectiva, el deseo o la necesidad del sujeto (Meinong, Ehrenfels, Perry).
  - **Objetivismo Axiológico**: Los valores son esencias ideales, absolutas, atemporales y objetivas, independientes de las apreciaciones humanas (Platón, Max Scheler, Nicolai Hartmann).



