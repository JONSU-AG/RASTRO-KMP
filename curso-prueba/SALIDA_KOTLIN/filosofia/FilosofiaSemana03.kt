## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Arché**: Principio primordial, elemento originario y sustrato constitutivo de todas las cosas en la filosofía griega presocrática.
2. **Tabula Rasa**: Metáfora empirista que describe la mente humana al nacer como una pizarra en blanco sin inscripciones.
3. **Epoché (\acute{\epsilon}\pi\mathrm{o}\chi\acute{\eta})**: Suspensión voluntaria del juicio ontológico o de valor; concepto central en el escepticismo pirrónico y la fenomenología de Husserl.
4. **Ataraxia**: Estado de imperturbabilidad, serenidad y sosiego del espíritu frente a las vicisitudes del mundo exterior.
5. **Noúmeno**: Concepto kantiano que designa la "cosa en sí", la realidad trascendente independiente de nuestra facultad cognoscitiva, incognoscible por la mente humana.
6. **Fenómeno**: La realidad tal como se manifiesta y es estructurada por las formas puras de la sensibilidad (espacio y tiempo) y los conceptos del entendimiento humano.
7. **A priori**: Aquello que es independiente de la experiencia sensible y posee validez universal y necesaria.
8. **A posteriori**: Aquello que deriva, se funda y depende enteramente de la experiencia empírica.
9. **Determinismo**: Doctrina filosófica que sostiene que todo acontecimiento está prefijado por una cadena inexorable de causas eficientes.
10. **Intersubjetividad**: Espacio de validez y comprensión compartido entre diversas conciencias racionales mediante la comunicación y el consenso reflexivo.

