## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **Diferencia entre Escepticismo Metódico y Radical**:
   - Si la duda es un **camino provisional** para hallar un principio indubitable (Descartes), es escepticismo metódico.
   - Si la duda es **permanente y concluye en la imposibilidad de la verdad** (Pirrón), es escepticismo radical.
2. **La trampa Fenómeno vs. Noúmeno en Kant**:
   - El *fenómeno* es lo que se conoce (objeto constituido por la sensibilidad y entendimiento).
   - El *noúmeno* (cosa en sí) **no se puede conocer**, solo se puede pensar como límite. Si una alternativa dice *"Kant afirmó que la ciencia conoce el noúmeno"*, es **falsa**.
3. **La trampa Subjetivismo vs. Relativismo**:
   - *Subjetivismo*: La verdad depende del sujeto individual (*"A mí me parece verdadero"*).
   - *Relativismo*: La verdad depende del contexto sociocultural o histórico (*"En la cultura incaica era verdadero, hoy no"*).

