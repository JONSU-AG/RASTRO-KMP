## 3. DESARROLLO TEÓRICO RIGUROSO



### B. El Problema del Conocimiento (Problema Gnoseológico)
Se descompone en tres dilemas nodales:

#### 1. Posibilidad del Conocimiento: ¿Puede el sujeto aprehender el objeto?
- **Dogmatismo**: Postura acrítica y optimista ingenua. Da por sentada la correspondencia plena entre pensamiento y realidad (Filosofía presocrática).
- **Escepticismo**: Duda o niega la posibilidad de conocer con certeza la realidad.
  - *Radical o Pirrónico* (Pirrón de Elis): La mente no puede alcanzar la verdad objetiva; recomienda la \acute{\epsilon}\pi\mathrm{o}\chi\acute{\eta} (*epoché*, suspensión del juicio) y la \dot{\alpha}\tau\alpha\rho\alpha\xi\acute{\iota}\alpha (*ataraxia*, imperturbabilidad del alma).
  - *Metódico* (René Descartes): Usa la duda como una herramienta temporal y sistemática para destruir el error y llegar a una certeza indubitable (*Cogito ergo sum*).
  - *Relativista / Subjetivista* (Protágoras: *"El hombre es la medida de todas las cosas"*): No hay verdad universal, depende del sujeto o la cultura.
  - *Agnosticismo* (David Hume, Thomas Huxley): Declara incognoscible lo que trasciende la experiencia sensible (Dios, el alma, la cosa en sí).
- **Criticismo** (Immanuel Kant): Postura intermedia y reflexiva. Establece que el conocimiento es posible, pero limitado rigurosamente al ámbito de los **fenómenos** (lo que se nos aparece mediante las formas a priori de la sensibilidad y el entendimiento), mientras que el **noúmeno** (la cosa en sí) es incognoscible.

#### 2. Origen del Conocimiento: ¿De dónde brota el saber legítimo?
- **Racionalismo** (Descartes, Spinoza, Leibniz): La fuente primordial es la **razón**. Poseemos ideas innatas o principios a priori independientes de la experiencia sensible. Las verdades matemáticas son su modelo supremo.
- **Empirismo** (John Locke, David Hume): La única fuente es la **experiencia sensible**. La mente al nacer es una *tabula rasa* (papel en blanco). No existen ideas innatas. *"Nada hay en el entendimiento que no haya estado antes en los sentidos"*.
- **Apriorismo / Criticismo Kantiano**: Síntesis integradora. El conocimiento comienza con la experiencia (materia), pero se estructura y organiza mediante las formas a priori de la mente humana (espacio, tiempo y categorías lógicas). *"Pensamientos sin contenido son vacíos; intuiciones sin conceptos son ciegas"*.
- **Intelectualismo** (Aristóteles, Santo Tomás): Postura intermedia clásica: la experiencia proporciona la materia prima y el intelecto abstrae las formas universales.

#### 3. Esencia del Conocimiento: ¿Qué determina a qué en el acto cognoscitivo?
- **Realismo**: El objeto existe independientemente del sujeto y determina las representaciones del sujeto.
- **Idealismo Gnoseológico**: El sujeto cognoscente determina, produce o constituye al objeto.
- **Fenomenalismo**: Solo conocemos las apariencias sensibles organizadas por nuestras facultades cognoscitivas (fenómenos), nunca las cosas tal como son en sí mismas.



### C. El Problema de la Verdad
1. **Teoría de la Correspondencia o Adecuación** (Aristóteles, Tomás de Aquino, Alfred Tarski):
   - Proposición: La verdad es la concordancia entre lo que se dice/piensa y la realidad de los hechos.
   - Fórmula aristotélica: *"Decir de lo que es que no es, o de lo que no es que es, es lo falso; decir de lo que es que es, y de lo que no es que no es, es lo verdadero"*.
2. **Teoría de la Coherencia** (Hegel, Racionalismo, Neurath):
   - La verdad de una proposición no se mide con el mundo empírico, sino con su no-contradicción respecto a un sistema formal o conjunto de proposiciones previamente aceptadas (modelo de la lógica y la geometría).
3. **Teoría Pragmática de la Verdad** (William James, Charles S. Peirce):
   - Una creencia o hipótesis es verdadera si funciona en la práctica, si es útil, genera consecuencias provechosas y resuelve problemas vitales.
4. **Teoría Consensual de la Verdad** (Jürgen Habermas):
   - La verdad es el acuerdo intersubjetivo alcanzado por los miembros de una comunidad de diálogo libre de coacciones externas.



### D. El Problema del Valor (Problema Axiológico)
- ¿Tienen las cosas valor porque las deseamos, o las deseamos porque tienen valor?
  - **Subjetivismo Axiológico**: El valor depende de la vivencia afectiva, el deseo o la necesidad del sujeto (Meinong, Ehrenfels, Perry).
  - **Objetivismo Axiológico**: Los valores son esencias ideales, absolutas, atemporales y objetivas, independientes de las apreciaciones humanas (Platón, Max Scheler, Nicolai Hartmann).



### E. El Problema de la Libertad
1. **Determinismo**:
   - Niega la libertad humana. Todo evento, incluidas las acciones humanas, está causalmente determinado por leyes naturales, biológicas, divinas o psíquicas (*Laplace, Spinoza, Skinner*).
2. **Indeterminismo**:
   - Afirma la existencia de rupturas en la cadena de causalidad, azar cuántico o libertad incausada absoluta.
3. **Autodeterminismo / Libertarismo Compatibilista**:
   - El ser humano reconoce las leyes naturales, pero posee la capacidad de deliberar, elegir y responsabilizarse moralmente (Kant: la libertad como postulado de la razón práctica; Jean-Paul Sartre: *"El hombre está condenado a ser libre"*).

