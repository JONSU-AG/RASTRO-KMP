## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa Salazar Bondy y el "calco y copia"**: Mariátegui acuñó la frase *"ni calco ni copia, sino creación heroica"* en 1928; Salazar Bondy en 1968 denunció que la filosofía latinoamericana fue lamentablemente un calco imitativo. No atribuir la frase de Mariátegui a Salazar Bondy.
2. **Bartolomé Herrera y la Soberanía Popular**: Herrera **aborrecía la soberanía popular**; afirmaba categóricamente la *soberanía de la inteligencia*. Si una alternativa señala que Herrera defendió el voto popular irrestricto, es totalmente falsa.
3. **El indio según González Prada vs. Deustua**:
   - González Prada consideró al indio víctima de la servidumbre feudal del hacendado y el cura, exigiendo su redención mediante la educación y la rebelión.
   - Deustua consideraba al indio una raza petrificada que no aportaba al progreso espiritual y por eso priorizaba la educación de la élite blanca/mestiza letrada.

