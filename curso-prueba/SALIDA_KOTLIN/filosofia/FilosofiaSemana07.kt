B) Demostró que la razón humana es una cualidad universal intrínseca a todos los pueblos, afirmando que ningún ser humano nace esclavo por naturaleza y que la soberanía indígena era legítima según el derecho de gentes.  
C) Respaldó el monopolio comercial de la Casa de Contratación de Sevilla sobre los metales preciosos del virreinato.  
D) Aplicó el método de la mayéutica socrática para reescribir las ordenanzas de la Real Audiencia de Lima.  
