## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Alienación Cultural**: Estado de despersonalización en el que una comunidad adopta como propios los esquemas mentales y valores impuestos por un poder hegemónico externo.
2. **Cosmovisión Andina**: Sistema holístico de creencias, símbolos y prácticas mediante el cual los pueblos andinos perciben y organizan su relación con la Pacha y la comunidad.
3. **Pacha**: Concepto ontológico andino que expresa la totalidad indisoluble del espacio, el tiempo, la materia viviente y el mundo cósmico.
4. **Yanantin**: Principio andino de complementariedad de opuestos (dualidad masculino-femenino, arriba-abajo, luz-oscuridad).
5. **Soberanía de la Inteligencia**: Tesis conservadora (Bartolomé Herrera) según la cual solo los ciudadanos con capacidad racional superior y formación moral tienen derecho a gobernar.
6. **Espiritualismo**: Corriente antipositivista de inicios del siglo XX que prioriza los valores morales, estéticos y la libertad creadora por encima de la utilidad material.
7. **Gamonalismo**: Sistema sociopolítico y económico semifeudal de dominación despótica ejercido por los terratenientes sobre la masa indígena campesina en el Perú andino.
8. **Filosofía de la Liberación**: Movimiento filosófico latinoamericano que busca desmantelar los mecanismos de dominación colonial y construir un pensamiento desde la alteridad del oprimido.
9. **Alteridad**: Reconocimiento del "Otro" en su diferencia irreductible, dignidad intrínseca y condición humana exterior al dominio del ego colonial.
10. **Lógica Jurídica**: Aplicación de los métodos formales y cálculos lógicos a la interpretación de normas jurídicas, desarrollada en el Perú por Francisco Miró Quesada Cantuarias.

