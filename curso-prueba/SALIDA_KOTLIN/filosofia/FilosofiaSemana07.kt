### B. Etapas de la Filosofía en el Perú

#### 1. El Pensamiento Prehispánico (Cosmovisión Andina)
- Debate: ¿Hubo filosofía en el Tahuantinsuyo? 
  - La mayoría de historiadores sostiene que hubo una **cosmovisión y pensamiento mítico-simbólico**, pero no una filosofía en sentido estricto (falta de argumentación lógica secular y escritura alfabética).
  - Principios rectores andinos: **Relacionalidad**, **Correspondencia**, **Complementariedad** (dualidad de opuestos complementarios: *yanantin*) y **Reciprocidad** (*ayni* y *minka*).
  - Categoría ontológica de la **Pacha**: integración indisociable de espacio y tiempo, naturaleza y comunidad sagrada.

#### 2. La Escolástica Colonial (s. XVI - XVIII)
- Se enseñó en la Real y Pontificia Universidad de San Marcos (fundada en 1551) y colegios mayores regentados por dominicos y jesuitas.
- **El Debate de Valladolid (1550 - 1551)**:
  - *Fray Bartolomé de las Casas*: Defensor de los indígenas. Sostuvo que los nativos americanos son seres humanos plenos, racionales y dotados de alma por Dios, debiendo ser evangelizados pacíficamente sin servidumbre forzada.
  - *Juan Ginés de Sepúlveda*: Basándose en la teoría de la "esclavitud natural" de Aristóteles, argumentó que los indígenas son seres inferiores, bárbaros e idólatras, justificando la guerra justa de conquista y dominación para imponerles la civilización y el cristianismo.

#### 3. La Ilustración Emancipadora (fines del s. XVIII - inicios del s. XIX)
- Desplazamiento progresivo del aristotelismo tomista por la física experimental de Newton y el racionalismo moderno.
- Núcleo difusor: La *Sociedad Amantes del País* y la revista **El Mercurio Peruano** (1791), donde se analiza científicamente la geografía, recursos e identidad de la patria peruana.
- Figuras señeras:
  - **Toribio Rodríguez de Mendoza**: Rector del Real Convictorio de San Carlos, formador intelectual de los patriotas emancipadores.
  - **Hipólito Unanue**: Médico, reformador científico y humanista (*Observaciones sobre el clima de Lima*).
  - **José Baquíjano y Carrillo**: Autor del célebre *Elogio al virrey Jáuregui* (1781), denuncia del despotismo virreinal tras la rebelión de Túpac Amaru II.

#### 4. El Romanticismo y el Debate Político Decimonónico (1826 - 1870)
Tras la proclamación de la República, se produjo la gran disputa doctrinaria sobre la naturaleza del Estado peruano:
- **Sector Conservador** (Liderado por el sacerdote **Bartolomé Herrera** desde el Colegio Guadalupe):
  - Defiende la **Soberanía de la Inteligencia**: la soberanía no reside en el pueblo iletrado, sino en la razón y la capacidad de las élites educadas llamadas por Dios a gobernar. Desconfianza profunda hacia la democracia popular y defensa del orden y la tradición católica.
- **Sector Liberal** (Liderado por **Benito Laso**, **Pedro Gálvez** y los hermanos José y Francisco de Paula González Vigil):
  - Defienden la **Soberanía Popular**: el poder emana de la voluntad ciudadana y del pacto social. Promueven el sufragio universal, la educación laica y la limitación estricta del poder clerical y militar.

#### 5. El Positivismo en el Perú (1880 - 1900)
Surge con fuerza tras el cataclismo nacional de la **Guerra del Guano y el Salitre (1879 - 1883)**. Se rechaza la retórica tradicional y se exige el imperio de la ciencia experimental y el trabajo productivo para reconstruir el país.
- **Manuel González Prada**: Máximo representante del positivismo combativo y anarquista radical.
  - Obras: *Pájinas libres* (1894, que incluye el *"Discurso en el Politeama"*: *"¡Los viejos a la tumba, los jóvenes a la obra!"*) y *Horas de lucha* (1908).
  - Crítica feroz a la triple alianza que arruinó al Perú: el clero católico oscurantista, el militarismo rapaz y la oligarquía política corrompida.
  - Reivindicación pionera del indígena: la opresión del indio no es un problema pedagógico, sino un problema socioeconómico de servidumbre feudal.
- **Manuel Vicente Villarán**: Positivismo universitario. En su célebre discurso de apertura del año académico en San Marcos (1900), demandó una reforma educativa radical: reemplazar la formación de literatos, teólogos y abogados improductivos por ingenieros, técnicos, agricultores y comerciantes utilitarios.

#### 6. La Reacción Espiritualista y Antipositivista (1900 - 1920)
Influenciada por el vitalismo de Henri Bergson. Cuestiona la reducción utilitarista del ser humano a máquina económica.
- **Alejandro Deustua**:
  - Máxima figura del espiritualismo peruano. Afirma que el valor supremo es la **libertad interna moral** y la contemplación estética creadora.
  - Concepción educativa: El Estado debe priorizar la **educación moral y estética de la élite directora** de la nación antes que la instrucción masiva de las clases bajas iletradas (*"El indio no es una persona que deba educarse mecánicamente, sino formarse espiritualmente"*).
  - Tesis: *"El orden es la libertad guiada por el bien"*.
- **Mariano Ibérico**: Filósofo del misticismo estético, el paisaje andino y la intuición existencial (*El sentimiento de la vida cósmica*).

#### 7. El Debate Ideológico Social de la Década de 1920 (Generación del Centenario)
- **José Carlos Mariátegui (Socialismo Indoamericano)**:
  - Obra cumbre: *7 ensayos de interpretación de la realidad peruana* (1928).
  - Aplica el método del materialismo histórico al análisis de la formación social peruana: la economía es semifeudal y semicolonial.
  - El problema del indio es el problema de la **tierra** (liquidación del gamonalismo y la servidumbre feudal mediante el colectivismo agrario indígena tradicional).
  - *"El socialismo en el Perú no debe ser calco ni copia, sino creación heroica de nuestro propio pueblo"*.
- **Víctor Raúl Haya de la Torre (Aprismo)**:
  - Obra cumbre: *El antimperialismo y el APRA* (1928) y *Espacio-Tiempo Histórico* (1948).
  - Relativiza la aplicación del marxismo europeo ortodoxo en América Latina (Indoamérica) mediante la teoría del "Espacio-Tiempo Histórico".
  - Sostiene que en Indoamérica el imperialismo no es la última fase del capitalismo, sino la primera fase que trae capital e industrias. Plantea un frente único de clases trabajadoras manuales e intelectuales y la nacionalización gradual de tierras e industrias dirigidas por un Estado antiimperialista.

#### 8. La Filosofía Contemporánea en el Perú (Segunda Mitad del s. XX)
- **Francisco Miró Quesada Cantuarias (1918 - 2019)**:
  - Fundador de la lógica moderna y la lógica jurídica en el Perú e Hispanoamérica.
  - Defiende un **humanismo solidario y de autodefensa**: la razón es la herramienta suprema para emancipar al hombre de la arbitrariedad y la violencia.
  - Desarrolló una profunda tipología de la filosofía latinoamericana distinguiendo a los patriarcas, los forjadores y la generación de la "asunción de la filosofía formal".

