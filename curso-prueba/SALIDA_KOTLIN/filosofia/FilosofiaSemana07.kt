### Nivel 5: Reto Extremo (Boss Challenge / UNI - UNSA Medicina)
**Enunciado**: En la controversia de Valladolid de 1550, Juan Ginés de Sepúlveda utilizó como eje de su argumentación la noción aristotélica de *esclavitud natural* para justificar la subordinación de los pueblos originarios de América. Por su parte, la réplica teológico-jurídica de Bartolomé de las Casas constituyó un hito fundacional en la historia del derecho natural moderno porque:
