## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Animal Simbólico**: Definición de Ernst Cassirer para el ser humano que resalta su capacidad única de estructurar el mundo mediante el lenguaje, el mito, el arte y la religión.
2. **Weltoffenheit (Apertura al Mundo)**: Término de Max Scheler que describe la libertad humana para distanciarse del entorno biológico instintivo y contemplar el cosmos objetivamente.
3. **Dignidad (*Würde*)**: Valor intrínseco, inalienable e inviolable de la persona humana que la sitúa por encima de todo precio o equivalencia económica.
4. **Hominización**: Proceso biológico evolutivo de transformación anatómica, neurológica y fisiológica que condujo al surgimiento del *Homo sapiens*.
5. **Humanización**: Proceso sociocultural y axiológico mediante el cual el ser humano desarrolla el lenguaje, la moral, las instituciones y la cultura espiritual.
6. **Praxis**: Actividad práctica, material y consciente mediante la cual el ser humano transforma activamente la naturaleza y la sociedad (Marx).
7. **Alienación**: Enajenación o extrañamiento en el cual el ser humano pierde el control de su propia creación (el trabajo, el Estado, la religión), convirtiéndose en víctima de ella.
8. **Existencia Precede a la Esencia**: Principio sartreano que estipula que el hombre surge en el mundo desprovisto de una naturaleza predeterminada y se autoconstruye con sus elecciones.
9. **Mala Fe**: En el existencialismo, actitud inauténtica de autoengaño en la cual una persona niega su propia libertad culpando a las circunstancias o al destino.
10. **Historicidad**: Condición ontológica del ser humano por la cual su modo de ser está íntimamente configurado por el devenir temporal y cultural de su época.

