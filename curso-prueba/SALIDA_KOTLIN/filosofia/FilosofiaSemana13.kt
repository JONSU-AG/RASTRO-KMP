### A. La Pregunta por el Hombre: Naturaleza y Objeto de Estudio
1. **Definición**: Disciplina filosófica que investiga la esencia, origen, sentido, finitud y peculiaridad ontológica del **ser humano** en el universo.
2. **La Pregunta Kantiana**: Immanuel Kant afirmó en su *Lógica* que todas las preguntas de la filosofía confluyen en una sola:
   - ¿Qué puedo saber? (\rightarrow Gnoseología y Epistemología).
   - ¿Qué debo hacer? (\rightarrow Ética y Moral).
   - ¿Qué me cabe esperar? (\rightarrow Filosofía de la Religión e Historia).
   - **¿Qué es el hombre?** (\rightarrow **Antropología Filosófica**).
3. **Diferenciación con las Antropologías Científicas**:
   - La *Antropología Física* estudia la evolución anatómica y biológica del *Homo sapiens*.
   - La *Antropología Cultural* describe los mitos, rituales y costumbres de sociedades particulares.
   - La *Antropología Filosófica* busca la **esencia universal**, la condición ontológica y la significación existencial del ser humano.



### C. Concepciones Filosóficas sobre la Esencia del Hombre

#### 1. El Hombre como Animal Racional (Aristóteles y el Pensamiento Clásico)
- Define al ser humano como un animal provisto de \lambda\acute{o}\gamma\mathrm{os} (*logos*: razón, pensamiento y lenguaje discursivo).
- La razón es la forma sustancial del alma humana que le permite conocer las esencias universales de las cosas, deliberar moralmente y organizar la vida política.

#### 2. El Hombre como Ser Espiritual (Max Scheler en *El puesto del hombre en el cosmos*, 1928)
- El animal está ligado a su entorno (*Umwelt*): reacciona de modo ciego ante estímulos biológicos de supervivencia guiado por instintos.
- El ser humano se define por poseer **Espíritu** (*Geist*). El espíritu se caracteriza por:
  - **Apertura al Mundo** (*Weltoffenheit*): Capacidad de distanciarse de los impulsos biológicos, objetivar la realidad circundante y contemplarla con libertad interior.
  - **Autoconciencia**: Capacidad de reflexionar sobre sí mismo y convertir su propia existencia en objeto de examen crítico.

#### 3. El Hombre como Animal Simbólico (Ernst Cassirer en *Antropología filosófica*, 1944)
- Corrige la definición tradicional de "animal racional": la razón es un término demasiado estrecho para abarcar toda la riqueza de la vida cultural humana.
- Entre el sistema receptor de estímulos y el sistema efector de respuestas, el ser humano ha intercalado un tercer eslabón exclusivo: el **sistema simbólico**.
- El hombre no vive en un universo puramente físico o natural, sino en un **universo simbólico**.
- El lenguaje, el mito, el arte, la ciencia y la religión son las formas simbólicas mediante las cuales el ser humano teje y da sentido a su realidad. El hombre es, en su raíz ontológica, un **Animal Simbólico** (*Animal symbolicum*).

#### 4. El Hombre como Ser Social y Productor (Karl Marx)
- Rechaza las esencias abstractas metafísicas eternas: *"La esencia humana no es algo abstracto inherente a cada individuo. Es, en su realidad, el conjunto de las relaciones sociales"*.
- El hombre se diferencia de los animales a partir del momento en que empieza a **producir sus propios medios de subsistencia mediante el trabajo material (*praxis*)**.
- Al transformar la naturaleza mediante el trabajo social consciente, el hombre se humaniza y transforma a sí mismo.
- **La Alienación del Trabajo**: En el modo de producción capitalista, el obrero queda desposeído del producto de su esfuerzo, transformando el trabajo (que debía ser su realización creadora) en una carga opresiva que lo deshumaniza y cosifica.

#### 5. El Hombre como Libertad y Proyecto Existencial (Jean-Paul Sartre)
- Existencialismo ateo: Al no existir Dios, no existe un diseño divino ni una "naturaleza humana" previa prefijada.
- Principio rector: **"La existencia precede a la esencia"**.
- El hombre primero existe, surge en el mundo, y solo después se autodefine mediante sus decisiones, proyectos y actos libres.
- *"El hombre no es otra cosa que lo que él se hace"*. La libertad humana es total e ineludible: estamos *"condenados a ser libres"*. La renuncia a elegir o el culpar al destino constituye un acto de "mala fe".

#### 6. El Hombre como Ser Histórico (Wilhelm Dilthey y José Ortega y Gasset)
- **Wilhelm Dilthey**: Las ciencias humanas no buscan explicar causas mecánicas como la física, sino *comprender* el sentido de las vivencias históricas.
- **José Ortega y Gasset**: Tesis célebre: *"El hombre no tiene naturaleza, sino que tiene historia"*.
  - El ser humano no es una cosa estática (como una piedra o un tigre, cuya esencia ya viene biológicamente programada), sino una tarea dramática que se inventa a cada instante: *"Yo soy yo y mi circunstancia, y si no la salvo a ella no me salvo yo"*.



