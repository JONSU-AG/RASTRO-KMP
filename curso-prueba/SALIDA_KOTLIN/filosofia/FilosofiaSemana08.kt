## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Alteridad**: Condición y reconocimiento del Otro en su singularidad ontológica, irreducible al propio Yo.
2. **Panoptismo**: Principio de vigilancia arquitectónica e institucional en el que los individuos están expuestos a una mirada potencialmente ininterrumpida que internaliza la disciplina.
3. **Biopolítica**: Conjunto de estrategias y dispositivos de poder gubernamental orientados a regular, controlar y administrar los procesos biológicos vitales de las poblaciones humanas.
4. **Metarrelato**: Gran marco narrativo y teleológico que pretende dar un sentido unitario y definitivo a la totalidad de la historia humana.
5. **Modernidad Líquida**: Categoría sociológica de Zygmunt Bauman que describe una sociedad desregulada donde las relaciones, empleos e instituciones cambian constantemente de forma sin solidificarse.
6. **Sociedad de Rendimiento**: Concepto de Byung-Chul Han para la sociedad actual donde los sujetos se autoexigen positividad y eficacia ilimitada, derivando en autoexplotación voluntaria.
7. **Burnout**: Colapso psicofísico o agotamiento vital crónico derivado del imperativo insaciable de rendimiento en la sociedad hiperconectada.
8. **Fusión de Horizontes**: Acontecimiento hermenéutico en el que el marco de comprensión del presente dialoga y se amplía al integrarse con el horizonte histórico del texto o tradición analizada.
9. **Razón Instrumental**: Racionalidad pragmática degradada que reduce el intelecto a un mero instrumento técnico de cálculo, eficacia y dominación calculadora.
10. **Intersubjetividad Comunicativa**: Teoría de Habermas que sitúa la racionalidad en el entendimiento dialógico entre personas libres mediante argumentos racionales y acuerdos libres de coacción.

