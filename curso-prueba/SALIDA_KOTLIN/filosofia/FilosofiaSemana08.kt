2. **Levinas y la reciprocidad**:
   - Levinas **rechaza que la ética se base en un contrato de reciprocidad simétrica** (*"Yo te cuido si tú me cuidas"*). Para él, la responsabilidad es incondicional, previa y asimétrica hacia el Otro.
3. **Byung-Chul Han y la coerción**:
   - El sujeto de la sociedad del cansancio **no es obligado con látigo por un capataz**; se explota a sí mismo bajo la ilusión de triunfar como proyecto personal de rendimiento.

