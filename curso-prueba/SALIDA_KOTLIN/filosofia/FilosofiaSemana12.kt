### C. Las Doctrinas Contractualistas Clásicas
En los siglos XVII y XVIII, la modernidad explica el origen legítimo del Estado a partir de un hipotético **Pacto o Contrato Social** que pone fin al **Estado de Naturaleza** (situación pre-política del ser humano):

#### 1. Thomas Hobbes (*Leviatán*, 1651) - El Absolutismo Protector
- **Estado de Naturaleza**: Todos los hombres son iguales en pasiones y fuerza física. Al no existir una autoridad que imponga orden, reina la desconfianza mutua y la competencia despiadada: el hombre es el lobo del hombre (*Homo homini lupus*). Es un estado permanente de **guerra de todos contra todos** (*Bellum omnium contra omnes*), donde la vida es *"solitaria, pobre, tosca, embrutecida y breve"*.
- **El Pacto Social**: Movidos por el miedo racional a la muerte violenta, los individuos ceden incondicionalmente todos sus derechos y libertades individuales a un soberano absoluto (un monarca o asamblea).
- **El Estado Resultante**: El **Leviatán**, monstruo bíblico terrenal dotado de poder coercitivo supremo e indivisible para garantizar la paz y el orden interior. El súbdito solo tiene derecho a resistir si el soberano intenta quitarle directamente la vida.

#### 2. John Locke (*Segundo tratado sobre el gobierno civil*, 1689) - El Liberalismo Clásico
- **Estado de Naturaleza**: Estado de relativa paz y libertad guiado por la ley moral natural racional. Los seres humanos poseen derechos naturales innatos e inalienables: **la Vida, la Libertad y la Propiedad Privada** (fundada en el trabajo).
- **El Problema**: Al no haber jueces imparciales, cada quien aplica la justicia por su propia mano, lo que genera incertidumbre e inseguridad jurídica cuando surgen controversias.
- **El Pacto Social**: Los hombres acuerdan formar la sociedad civil y el Estado mediante un pacto de confianza revocable, cediendo únicamente el derecho de castigar y hacer justicia por cuenta propia.
- **El Estado Resultante**: **Estado Liberal Constitucional** con división de poderes (Legislativo y Ejecutivo). El poder estatal es limitado: si los gobernantes violan los derechos naturales de los ciudadanos, estos tienen el legítimo **Derecho de Rebelión** para derrocar al gobierno tiránico.

#### 3. Jean-Jacques Rousseau (*El contrato social*, 1762) - La Democracia Radical
- **Estado de Naturaleza**: El ser humano nace bueno, libre, piadoso y feliz en armonía con la naturaleza (**El Buen Salvaje**).
- **La Corrupción Histórica**: La invención de la **propiedad privada** y la división del trabajo introdujeron la desigualdad social, el egoísmo, la opresión y la guerra (*"El primer hombre que cercó un terreno y dijo: 'Esto es mío', y encontró gente bastante simple para creerle, fue el verdadero fundador de la sociedad civil"*).
- **El Pacto Social**: No se trata de volver a la selva primitiva, sino de fundar un nuevo contrato legítimo en el que cada asociado pone su persona y todo su poder bajo la dirección suprema de la **Voluntad General** (*Volonté Générale*).
- **El Estado Resultante**: **Democracia Directa y Soberanía Popular Inalienable**. Al obedecer a la ley emanada de la Voluntad General (que busca siempre el bien común colectivo y no los intereses privados particulares), el ciudadano se obedece a sí mismo y permanece tan libre como antes.



### D. Teorías de la Justicia: John Rawls y el Liberalismo Igualitario
En su monumental obra *Teoría de la Justicia* (1971), John Rawls revitaliza el contractualismo frente al utilitarismo.
1. **La Posición Original y el Velo de la Ignorancia**:
   - Experimento mental: Para definir qué es una sociedad justa, imaginemos a representantes racionales deliberando en una **Posición Original** bajo el **Velo de la Ignorancia** (*Veil of Ignorance*).
   - Ninguno sabe qué lugar ocupará en la sociedad: ignora su clase social, su raza, su género, sus talentos biológicos, su inteligencia ni su religión.
   - En esa situación de incertidumbre absoluta, cualquier individuo racional elegirá una estructura social que proteja a los menos favorecidos (estrategia *maximin*).
2. **Los Dos Principios de Justicia de Rawls**:
   - **Primer Principio (Principio de Mayor Libertad Igual)**: Cada persona tiene un derecho igual al esquema más amplio de libertades básicas compatibles con una libertad similar para todos (libertad de conciencia, de expresión, de voto, integridad física). Tiene prioridad léxica inquebrantable.
   - **Segundo Principio**: Las desigualdades socioeconómicas solo son justas si satisfacen dos condiciones:
     1. Deben estar vinculadas a puestos accesibles a todos en condiciones de **Justa Igualdad de Oportunidades**.
     2. **El Principio de Diferencia**: Las desigualdades existentes deben redundar en el **mayor beneficio posible de los miembros más desaventajados** de la sociedad.



