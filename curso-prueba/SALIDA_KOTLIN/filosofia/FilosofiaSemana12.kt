## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **La trampa Hobbes vs. Locke sobre la propiedad**:
   - Para Hobbes, la propiedad la crea el Estado y el soberano puede expropiarla si lo juzga necesario para el orden público.
   - Para Locke, la propiedad es un **derecho natural previo al Estado**, y el Estado solo existe para protegerla.
2. **Voluntad General vs. Voluntad de Todos en Rousseau**:
   - *Voluntad de Todos*: Simple suma matemática de los intereses egoístas y privados de cada persona.
   - *Voluntad General*: Voluntad que apunta exclusivamente al **bien común e interés público** colectivo. Si una alternativa confunde ambas, es falsa.
3. **El Velo de la Ignorancia de Rawls**: Los deliberantes no son ignorantes de la economía o sociología; conocen las leyes generales del mundo, pero **ignoran su propia posición personal** dentro de la sociedad.

