## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Zoon Politikón**: Concepto aristotélico que define al hombre como una entidad naturalmente sociable cuya vida adquiere plenitud en la polis.
2. **Estado de Naturaleza**: Condición hipotética y prepolítica en la que vivía la humanidad antes de la institución del orden civil y de las leyes positivas.
3. **Pacto Social**: Acuerdo racional y deliberado mediante el cual los individuos instituyen la sociedad civil y erigen la autoridad política legítima.
4. **Leviatán**: Metáfora hobbesiana del Estado soberano absoluto, concebido como un dios mortal que concentra el poder coercitivo indiscutible.
5. **Voluntad General**: Concepto rousseauniano que designa la voluntad soberana del cuerpo de ciudadanos orientada siempre hacia el bien común colectivo.
6. **Posición Original**: Situación hipotética de deliberación ideada por John Rawls para deducir imparcialmente los principios distributivos de una sociedad justa.
7. **Velo de la Ignorancia**: Mecanismo de justicia rawlsiano que priva a los pactantes del conocimiento de sus ventajas o desventajas personales para asegurar equidad.
8. **Principio de Diferencia**: Criterio de justicia según el cual las desigualdades sociales son permisibles solo si benefician al estrato más desaventajado.
9. **Virtù (Maquiavelo)**: Temple, destreza, valentía y sagacidad política del gobernante para dominar las contingencias de la Fortuna y retener el poder.
10. **Banalidad del Mal**: Condición analizada por Hannah Arendt donde el mal masivo no brota de una maldad demoníaca, sino de la renuncia al pensamiento crítico y la obediencia ciega a las órdenes burocráticas.

