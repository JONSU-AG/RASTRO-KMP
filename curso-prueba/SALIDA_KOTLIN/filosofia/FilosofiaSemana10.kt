6. **Imperativo Categórico**: Mandato moral universal, incondicionado y a priori formulado por la razón práctica kantiana.
7. **Imperativo Hipotético**: Norma instrumental que ordena una acción solo como medio condicionado para alcanzar un fin ulterior.
8. **Heteronomía Moral**: Estado en que la voluntad del individuo es guiada por leyes, presiones, dogmas o castigos impuestos desde el exterior.
9. **Autonomía Moral**: Capacidad suprema de la razón humana para darse a sí misma su propia ley moral universal sin coacciones externas.
10. **Principio de Utilidad**: Criterio consecuencialista que prescribe juzgar las acciones en función del bienestar o felicidad general que producen en los afectados.

