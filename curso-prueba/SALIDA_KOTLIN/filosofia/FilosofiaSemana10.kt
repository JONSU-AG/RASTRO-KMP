## 6. CASUÍSTICA Y "HACKING" DE EXÁMENES (TRAMPAS FRECUENTES)
1. **Inmoral vs. Amoral**:
   - **Inmoral**: Quien tiene conciencia y libertad, conoce la norma pero **decide violarla deliberadamente** (ej. un ladrón que planifica un robo).
   - **Amoral**: Quien **carece de conciencia moral o libertad** para discernir el bien del mal; está fuera del ámbito moral (ej. un infante de dos meses, un lobo que caza a una oveja o una persona con demencia senil avanzada).
2. **Imperativo Categórico vs. Hipotético en Kant**:
   - Hipotético: Condicional (*"Si quieres aprobar, debes estudiar"*). No tiene valor moral puro; es una regla de habilidad pragmática.
   - Categórico: Incondicional y absoluto (*"No debes mentir bajo ninguna circunstancia"*).
3. **Epicuro no es placer carnal desbocado**: Muchos estudiantes confunden el hedonismo de Epicuro con el desenfreno orgiástico (hedonismo cirenaico de Aristipo). Epicuro recomendaba pan, agua, tertulias con amigos y dominio de los deseos vanos.

