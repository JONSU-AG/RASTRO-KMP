### C. Las Grandes Doctrinas Éticas de la Historia

#### 1. Éticas Teleológicas o Materiales (Orientadas al Fin o al Bien)
- **Eudemonismo de Aristóteles** (*Ética a Nicómaco*):
  - El fin supremo (*telos*) de toda acción humana es la **felicidad** (\epsilon\hat{\upsilon}\delta\alpha\iota\mu\mathrm{o}\nu\acute{\iota}\alpha, *eudaimonía*).
  - La verdadera felicidad no reside en las riquezas perecederas, los honores efímeros ni los placeres groseros, sino en el **ejercicio continuo de la actividad racional** conforme a la virtud.
  - *La Teoría del Justo Medio*: La virtud moral es el hábito electivo que consiste en una posición intermedia entre dos vicios extremos: el exceso y el defecto.
    - Ejemplo: La **valentía** es el término medio entre la cobardía (defecto de arrojo) y la temeridad (exceso irreflexivo).
- **Hedonismo de Epicuro de Samos** (*Carta a Meneceo*):
  - El bien supremo es el **placer** (\dot{\eta}\delta\mathrm{o}\nu\acute{\eta}, *hedoné*) y la ausencia de dolor.
  - Hedonismo Racional: Epicuro no defiende el desenfreno sensorial desbocado (que acarrea resaca y sufrimiento), sino el placer espiritual, la serenidad y la sobriedad.
  - Objetivo dual: La **Aponía** (ausencia de dolor físico) y la **Ataraxia** (imperturbabilidad y paz del alma).
  - Distingue placeres: naturales y necesarios (comer con moderación, amistad), naturales no necesarios (manjares exquisitos) e innaturales e innecesarios (fama, poder, riquezas vanas).
- **Utilitarismo (Jeremy Bentham y John Stuart Mill)**:
  - Ética consecuencialista nacida en la Inglaterra de la Revolución Industrial.
  - **Principio de Mayor Felicidad**: Una acción es moralmente buena si tiende a promover la mayor cantidad neta de felicidad o bienestar para el mayor número de personas afectadas.
  - *Jeremy Bentham*: Utilitarismo cuantitativo (cálculo aritmético del placer: intensidad, duración, certeza, cercanía).
  - *John Stuart Mill*: Utilitarismo cualitativo. Distingue entre placeres inferiores (corporales) y placeres superiores (intelectuales, artísticos y morales). Tesis célebre: *"Es mejor ser un humano insatisfecho que un cerdo satisfecho; es mejor ser Sócrates insatisfecho que un tonto satisfecho"*.

#### 2. Éticas Deontológicas o del Deber (Orientadas a la Norma Pura)
- **El Formalismo Deontológico de Immanuel Kant** (*Fundamentación de la metafísica de las costumbres*):
  - Rechaza las éticas materiales y teleológicas por ser empíricas, heterónomas e hipotéticas (*"Si quieres ser feliz, entonces haz X"*).
  - La moral auténtica debe ser **a priori, autónoma y formal** (no prescribe contenidos concretos, sino la forma universal de la voluntad).
  - Lo único intrínsecamente bueno sin restricción es la **Buena Voluntad**: la voluntad que actúa exclusivamente **por deber** y no por inclinación, conveniencia o miedo.
  - Tipos de acciones frente al deber:
    1. Acciones contrarias al deber (inmorales; ej. estafar a un cliente).
    2. Acciones conformes al deber por inclinación (legalmente correctas pero moralmente neutras; ej. cobrar el precio justo para no perder clientela).
    3. Acciones realizadas estrictamente **por puro respeto al deber** (las únicas con genuino valor moral; ej. devolver el dinero por deber aunque nadie nos observe y nos perjudique económicamente).
  - **El Imperativo Categórico**: Mandato moral incondicional y absoluto de la razón práctica.
    - *Primera formulación (Universalidad)*: *"Obra solo según una máxima tal que puedas querer al mismo tiempo que se torne ley universal"*.
    - *Segunda formulación (Dignidad Humana)*: *"Obra de tal modo que trates a la humanidad, tanto en tu persona como en la persona de cualquier otro, siempre como un fin y nunca simplemente como un medio"*.

#### 3. Otras Corrientes Éticas Contemporáneas
- **Axiología Ética (Max Scheler)**: El bien moral consiste en preferir los valores superiores sobre los inferiores según una jerarquía objetiva dada a la intuición emocional.
- **Ética del Discurso (Jürgen Habermas y Karl-Otto Apel)**: La validez de una norma moral se fundamenta en el **consenso universal** alcanzado por los afectados en una comunidad ideal de diálogo libre de coacciones.



### D. Bioética y Dilemas Morales Contemporáneos
La Bioética (disciplina acuñada por Van Rensselaer Potter en 1971) aplica la reflexión ética a los dilemas de las ciencias de la vida, la medicina y la tecnología.
- **Los Cuatro Principios Bioéticos de Beauchamp y Childress**:
  1. **Principio de Autonomía**: Respeto irrestricto a la capacidad de decisión informada del paciente sobre su propio cuerpo (Consentimiento Informado).
  2. **Principio de Beneficencia**: Obligación moral de actuar siempre buscando el mayor bien y alivio del paciente.
  3. **Principio de No Maleficencia**: Obligación primordial de no causar daño intencional al paciente (*Primum non nocere*).
  4. **Principio de Justicia**: Distribución equitativa y solidaria de los recursos sanitarios, cargas y beneficios en la sociedad sin discriminación.
- **El Dilema del Tranvía (Philippa Foot y Judith Jarvis Thomson)**:
  - Un tranvía sin frenos va a matar a 5 operarios. Puedes mover una palanca para desviarlo y matar a 1 solo operario inocente.
  - *Respuesta Utilitarista*: Mueve la palanca (5 > 1; maximiza el número de vidas salvadas).
  - *Respuesta Deontológica / Kantiana*: No puedes utilizar la vida de una persona como mero instrumento o medio descartable para salvar a otras, pues violarías su dignidad intrínseca.

