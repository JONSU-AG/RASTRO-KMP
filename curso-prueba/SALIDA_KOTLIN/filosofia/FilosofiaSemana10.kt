## 3. DESARROLLO TEÓRICO RIGUROSO



### A. Distinción Conceptual: Moral vs. Ética
1. **Etimología**:
   - *Moral*: Proviene del latín *mos, moris* ("costumbre, hábito, modo de vivir").
   - *Ética*: Proviene del griego \tilde{\eta}\theta\mathrm{os} (*ethos*, "carácter, morada interior, modo de ser adquirido").
2. **Diferenciación Teórica**:
   - **Moral (Moral Vivida)**: Conjunto de normas, valores, prohibiciones, costumbres y prescripciones históricas y culturales que regulan la conducta efectiva de los miembros de una sociedad específica. Es fáctica, particular y mutable en el tiempo.
   - **Ética (Moral Pensada)**: Disciplina filosófica que toma a la moral como objeto de estudio. No crea las normas sociales, sino que **las analiza críticamente, fundamenta racionalmente su validez**, cuestiona su universalidad e indaga por la naturaleza del Bien y la Vida Buena.



### B. La Persona Moral y el Acto Moral
No toda acción humana es un acto moral; solo lo son aquellas ejecutadas por una **persona moral**.
1. **Condiciones Indispensables de la Persona Moral**:
   - **Conciencia Moral**: Capacidad reflexiva del sujeto para discernir racionalmente entre lo correcto y lo incorrecto, el bien y el mal.
   - **Libertad Moral**: Capacidad de autodeterminación de la voluntad para elegir entre alternativas de acción sin coacción externa insuperable ni necesidad ciega.
   - **Responsabilidad Moral**: Obligación moral y jurídica de asumir plenamente las consecuencias derivadas de los propios actos libres y conscientes.
   - *Caso Especial*: Los niños pequeños, los orates o personas con afecciones mentales graves que anulan el discernimiento carecen de imputabilidad moral (son sujetos **amorales**, no inmorales).
2. **Estructura Interna del Acto Moral**:
   - **Motivo o Intención**: El impulso o causa subjetiva que mueve a actuar.
   - **Conciencia del Fin**: La representación mental anticipada del objetivo que se pretende alcanzar.
   - **Medios**: Los instrumentos o vías empleadas para materializar el fin. (Principio ético: el fin no justifica cualquier medio inmoral).
   - **Deliberación y Elección Libre**: El pesaje racional de las opciones y la decisión de la voluntad.
   - **Resultado y Consecuencias**: La plasmación fáctica del acto en el mundo y sus efectos sobre otros seres conscientes.



### D. Bioética y Dilemas Morales Contemporáneos
La Bioética (disciplina acuñada por Van Rensselaer Potter en 1971) aplica la reflexión ética a los dilemas de las ciencias de la vida, la medicina y la tecnología.
- **Los Cuatro Principios Bioéticos de Beauchamp y Childress**:
  1. **Principio de Autonomía**: Respeto irrestricto a la capacidad de decisión informada del paciente sobre su propio cuerpo (Consentimiento Informado).
  2. **Principio de Beneficencia**: Obligación moral de actuar siempre buscando el mayor bien y alivio del paciente.
  3. **Principio de No Maleficencia**: Obligación primordial de no causar daño intencional al paciente (*Primum non nocere*).
  4. **Principio de Justicia**: Distribución equitativa y solidaria de los recursos sanitarios, cargas y beneficios en la sociedad sin discriminación.
- **El Dilema del Tranvía (Philippa Foot y Judith Jarvis Thomson)**:
  - Un tranvía sin frenos va a matar a 5 operarios. Puedes mover una palanca para desviarlo y matar a 1 solo operario inocente.
  - *Respuesta Utilitarista*: Mueve la palanca (5 > 1; maximiza el número de vidas salvadas).
  - *Respuesta Deontológica / Kantiana*: No puedes utilizar la vida de una persona como mero instrumento o medio descartable para salvar a otras, pues violarías su dignidad intrínseca.

