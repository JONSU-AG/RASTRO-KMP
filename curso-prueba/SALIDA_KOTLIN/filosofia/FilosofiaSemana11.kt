### Nivel 4: Análisis Crítico / Modelo DECO - UNSA
**Enunciado**: Lea con atención el siguiente fragmento de Max Scheler:
> *"Los valores no son cosas, ni propiedades de cosas, ni estados psíquicos subjetivos. Son esencias que se dan a nosotros a través de una intuición emocional pura. Así como hay un ver con los ojos físicos, hay un percibir afectivo mediante el cual captamos la jerarquía eterna de lo bueno, lo bello y lo sagrado, independientemente de nuestros apetitos mudables"*. (*El formalismo en la ética y la ética material de los valores*).

Del texto citado se deduce que la postura de Scheler:
A) Es un subjetivismo relativista que condiciona el valor al mercado comercial.  
B) Reduce la moralidad a un cálculo hedonista de placer sensorial.  
C) Defiende un objetivismo axiológico sustentado en la captación intuitivo-emocional de esencias ideales universales.  
D) Niega la existencia de cualquier orden jerárquico entre los valores espirituales.  
E) Considera que los valores son ficciones lingüísticas originadas en el lenguaje formal.  

- **Resolución**: Scheler defiende un **objetivismo axiológico**: los valores son esencias ideales autónomas que no dependen de la psique humana ni de las cosas físicas, captadas a través de la intuición emocional (*Wertfühlen*), lo que descarta el subjetivismo y consagra la objetividad del orden axiológico.
- **Clave Correcta**: **C**

