## 3. DESARROLLO TEÓRICO RIGUROSO



### A. Concepto de Valor y el Acto Valorativo
1. **Definición**: El valor es una cualidad estructural especial que atribuimos a las cosas, acciones o personas, en virtud de la cual provocan nuestra adhesión, estimación, atracción o rechazo.
2. **Bienes vs. Valores**:
   - Los **Bienes** son los objetos o entidades reales portadoras de valor (un cuadro de lienzo, una acción heroica, una ley escrita). Tienen peso, ocupan espacio y se pueden destruir físicamente.
   - Los **Valores** son cualidades ideales que se encarnan en los bienes. La tela puede quemarse, pero la belleza o la justicia no se queman.
3. **El Acto Valorativo**: Vivencia interior mediante la cual un sujeto toma postura a favor o en contra de un objeto o hecho:
   - *Momento Cognoscitivo*: Percepción y comprensión de las propiedades del objeto.
   - *Momento Afectivo*: Sentimiento de simpatía, agrado, aversión o desagrado que despierta el objeto en nuestra intimidad.
   - *Momento Activo / Volitivo*: Decisión de aceptar, rechazar, buscar o destruir el objeto según la valoración efectuada.
4. **Juicio de Hecho vs. Juicio de Valor**:
   - **Juicio de Hecho**: Proposición puramente descriptiva, objetiva, neutral y verificable que constata una realidad física o empírica tal como es, sin juzgarla moral o estéticamente.
     - *Ejemplo*: *"El nevado Mismi tiene una altitud de 5597 m s. n. m."* o *"El cobre es un buen conductor térmico"*.
   - **Juicio de Valor**: Proposición evaluativa o estimativa que expresa una calificación, preferencia o rechazo subjetivo u objetivo respecto al mérito de las cosas.
     - *Ejemplo*: *"El nevado Mismi es el paraje más majestuoso de Arequipa"* o *"La cobardía es una conducta repudiable"*.



### B. Características Esenciales del Valor
Las cuatro propiedades inseparables del valor evaluadas en exámenes de admisión:
1. **Polaridad**:
   - Todo valor se desdobla necesariamente en dos polos opuestos y contradictorios: un **polo positivo** (valor propiamente dicho) y un **polo negativo** (antivalor, disvalor o contravalor).
   - No hay valor neutral: frente al valor siempre existe su opuesto.
   - *Ejemplos*: Bello \leftrightarrow Feo; Bueno \leftrightarrow Malo; Justo \leftrightarrow Injusto; Verdadero \leftrightarrow Falso; Sagrado \leftrightarrow Profano; Salud \leftrightarrow Enfermedad.
2. **Jerarquía**:
   - Los valores no están en el mismo plano horizontal; se ordenan en una escala donde unos son considerados superiores o más dignos que otros.
   - La jerarquía orienta las decisiones humanas fundamentales (ej. preferir la dignidad o la verdad por encima de la comodidad económica o el placer sensible).
3. **Gradualidad**:
   - Variación cuantitativa o de intensidad con que un mismo valor se manifiesta en distintos objetos o circunstancias concretas.
   - Expresa grados de perfección dentro del mismo polo: excelente, óptimo, muy bueno, regular, deficiente, pésimo.
4. **Infinitud**:
   - Los valores representan arquetipos ideales o metas universales inagotables que ninguna realización empírica finita logra colmar por completo (la justicia perfecta jamás se realiza de modo absoluto en una sola sentencia terrenal).



