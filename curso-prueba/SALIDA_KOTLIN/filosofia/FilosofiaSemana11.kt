### Nivel 1: Básico / Definición Directa
**Enunciado**: La propiedad del valor que establece que a todo valor positivo le corresponde necesariamente un polo opuesto o negativo (como bello frente a feo, o justo frente a injusto) se denomina:
A) Gradualidad  
B) Jerarquía  
C) Polaridad  
D) Infinitud  
E) Inmanencia  

- **Resolución**: La **polaridad** es la característica axiológica fundamental por la cual los valores se presentan siempre desdoblados en una dimensión positiva y su respectivo contravalor o antivalor negativo.
- **Clave Correcta**: **C**

---



### B. Características Esenciales del Valor
Las cuatro propiedades inseparables del valor evaluadas en exámenes de admisión:
1. **Polaridad**:
   - Todo valor se desdobla necesariamente en dos polos opuestos y contradictorios: un **polo positivo** (valor propiamente dicho) y un **polo negativo** (antivalor, disvalor o contravalor).
   - No hay valor neutral: frente al valor siempre existe su opuesto.
   - *Ejemplos*: Bello \leftrightarrow Feo; Bueno \leftrightarrow Malo; Justo \leftrightarrow Injusto; Verdadero \leftrightarrow Falso; Sagrado \leftrightarrow Profano; Salud \leftrightarrow Enfermedad.
2. **Jerarquía**:
   - Los valores no están en el mismo plano horizontal; se ordenan en una escala donde unos son considerados superiores o más dignos que otros.
   - La jerarquía orienta las decisiones humanas fundamentales (ej. preferir la dignidad o la verdad por encima de la comodidad económica o el placer sensible).
3. **Gradualidad**:
   - Variación cuantitativa o de intensidad con que un mismo valor se manifiesta en distintos objetos o circunstancias concretas.
   - Expresa grados de perfección dentro del mismo polo: excelente, óptimo, muy bueno, regular, deficiente, pésimo.
4. **Infinitud**:
   - Los valores representan arquetipos ideales o metas universales inagotables que ninguna realización empírica finita logra colmar por completo (la justicia perfecta jamás se realiza de modo absoluto en una sola sentencia terrenal).



### Nemotecnia de las 4 Características del Valor:
> **"PO - JE - GRA - IN"**
- **PO**: **Po**laridad (Todo valor tiene su antivalor: Bueno \leftrightarrow Malo)
