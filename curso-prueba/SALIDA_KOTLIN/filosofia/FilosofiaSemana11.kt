### C. El Gran Debate Axiológico: Subjetivismo vs. Objetivismo

#### 1. Corriente Subjetivista
Sostiene que las cosas no tienen valor en sí mismas; el valor es una **proyección psíquica, afectiva o cultural del sujeto**. *"Las cosas valen porque las deseamos o nos agradan"*.
- **Alexius Meinong (Afectivismo del Agrado)**:
  - Una cosa tiene valor si y solo si nos produce agrado, gozo o placer sentimental. Si un objeto no despierta ningún agrado en nosotros, carece por completo de valor.
- **Christian von Ehrenfels (Afectivismo del Deseo)**:
  - Corrige a Meinong: muchas cosas nos agradan pero no las valoramos tanto como aquellas que no tenemos.
  - El valor reside en el **deseo**: valoramos aquello que deseamos y apetecemos, especialmente lo que es escaso o inaccesible.
- **Ralph Barton Perry (Teoría del Interés)**:
  - El valor es cualquier objeto de cualquier interés. El interés de un sujeto confiere inmediatamente valor al objeto hacia el cual se dirige.

#### 2. Corriente Objetivista
Sostiene que los valores son **independientes del sujeto** cognoscente, de sus apetitos, deseos y de los bienes materiales en que se encarnan. *"Deseamos las cosas porque son valiosas en sí mismas"*. Aunque nadie aprecie un cuadro bello o una conducta justa, el valor belleza y justicia siguen existiendo objetivamente.
- **Platón (Idealismo Absoluto)**: Los valores son Ideas eternas, perfectas e inmutables que habitan en el *Topos Uranos*.
- **Max Scheler (Fenomenología Axiológica)**:
  - Las obras cumbres: *El formalismo en la ética y la ética material de los valores* (1916).
  - Los valores son **esencias alógicas e ideales**, cualidades puras independientes de las cosas y de la mente humana.
  - No se captan mediante la razón discursiva abstracta ni por los sentidos físicos, sino a través de una facultad innata especial: la **intuición emocional o sentimiento de valor** (*Wertfühlen*).
  - *La Jerarquía Axiológica de Max Scheler* (de menor a mayor jerarquía):
    1. **Valores de lo Agradable / Hedónicos**: Placentero vs. desagradable; gozo vs. dolor.
    2. **Valores Vitales**: Salud vs. enfermedad; vigor vs. debilidad; noble vs. vulgar.
    3. **Valores Espirituales**:
       - *Estéticos*: Bello vs. feo.
       - *Jurídicos*: Justo vs. injusto.
       - *Intelectuales o del puro conocimiento*: Verdadero vs. falso.
    4. **Valores Religiosos o de lo Sagrado**: Sagrado vs. profano; santo vs. pecaminoso (constituyen la cúspide incondicional de su tabla axiológica).

#### 3. Corrientes Contemporáneas: Relacionismo y Sociologismo
- **Relacionismo Estructural (Risieri Frondizi en *¿Qué son los valores?*)**:
  - Supera la dicotomía estéril entre subjetivismo y objetivismo.
  - El valor no es una cosa inerte en el objeto ni una pura fantasía en el sujeto: el valor surge como una **cualidad estructural que brota de la relación dialéctica y dinámica entre el Sujeto, el Objeto y la Situación concreta**.

