## 8. GLOSARIO TÉCNICO DE 10 TÉRMINOS FILOSÓFICOS
1. **Axios**: Vocablo griego que significa digno de estima, valioso, honorable o apreciable.
2. **Bien**: Objeto material o ente concreto que encarna o porta un determinado valor espiritual, estético o moral.
3. **Polaridad**: Propiedad axiológica por la cual todo valor se manifiesta en oposición a un antivalor o disvalor recíproco.
4. **Gradualidad**: Rango de variación en el grado de realización o intensidad con que se experimenta un valor determinado.
5. **Afectivismo**: Corriente subjetivista que fundamenta el origen del valor en las vivencias de agrado o en los impulsos del deseo.
6. **Intuición Emocional (*Wertfühlen*)**: Facultad sentimental pura de la conciencia humana mediante la cual se aprehenden directamente los valores objetivos (Scheler).
7. **Valores Sagrados**: Estrato superior de la jerarquía de Max Scheler vinculado a las vivencias de la fe, la santidad y la adoración.
8. **Relacionismo**: Posición integradora que sostiene que el valor emerge de la síntesis interactiva entre sujeto, objeto y situación.
9. **Juicio Estimativo**: Proposición lingüística que expresa la atribución de un valor a un hecho u objeto.
10. **Tabula de Valores**: Escala ordenada de prioridades axiológicas que guía las elecciones morales y vitales de una persona o comunidad.

